export function appendPreparationSystemGuidance(messages: ChatMessage[], guidance: string): ChatMessage[] {
  const next = messages.map(message => ({ ...message }))
  const system = next.find(message => message.role === 'system')
  if (system) system.content += `\n\n${guidance}`
  else next.unshift({ role: 'system', content: guidance })
  return next
}

export function researchContentGuidance(mode: 'scene' | 'plan' | 'sources' = 'scene', hasSuppliedSources = false): string {
  const task = mode === 'plan'
    ? '只制订研究计划：先确定会改变本场景的关键疑问，再列需要什么原始材料、核对什么及优先顺序。没有材料就不要先回答具体制度、年代、工资、服饰或行话；不为填原模板四小节而编细节。年代与地区是作者暂定选择，不因出现在输入里就成为已考证锚点。可以先写不依赖待核实制度的生活动作或明确架空的试稿；研究不是准许作者落笔的门槛。'
    : mode === 'sources'
      ? '只审读作者提供资料：把“资料写了什么”和“现实中已经证实什么”分开，作者提供或声明可靠不等于系统核验。不同地点/年份不先判冲突，不必强行调和，更不能默认为同一制度；需要架空组合时单列创作提议。登记摘录不能直接推断官方制度、普遍惯例或自然周期。无资料时只说明材料需求。先逐条限于摘录作答，再给至多一个简短生活用法；不要扩写未提供的服饰、器物工艺、称谓或百科清单，更不能将它们标成可直接采用的事实。'
      : '分析当前场景的设定兼容、待考证点与可用写作细节；不把未发现矛盾写成史实全部核实。'
  return `${RESEARCH_CONTENT_GUIDANCE}
本轮动作：${task}
本轮${hasSuppliedSources ? '读取了登记参考或作者提供资料（仍未由本系统核验）' : '未读取到可用外部资料'}；未执行联网检索。按本轮动作组织标题，不强填原模板中不适用的小节。`
}

export function appendResearchTaskGuidance(
  messages: ChatMessage[],
  mode: 'scene' | 'plan' | 'sources' = 'scene',
  hasSuppliedSources = false,
): ChatMessage[] {
  const next = appendPreparationSystemGuidance(messages, researchContentGuidance(mode, hasSuppliedSources))
  const action = mode === 'plan'
    ? '研究计划：只交关键问题、材料需求、优先顺序和可暂写的范围。'
    : mode === 'sources'
      ? '已有资料审读：只交资料各自支持的内容、冲突/范围判断、缺口及一个简短生活用法。'
      : '场景与设定分析：按当前场景需要组织建议，分别标明依据、待核实项与创作提议。'
  next.push({ role: 'user', content: `【本轮已选择任务】${action}此前模板的通用四段结构仅在适用时参考，不另行扩写百科、情节冲突或冒称完成检索。` })
  return next
}
