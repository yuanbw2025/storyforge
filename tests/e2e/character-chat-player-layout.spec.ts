import {test, expect} from '@playwright/test'
import {openChatNarrativeTools} from './helpers/character-chat-ui'

for (const width of [390, 1440]) test(`chat and composer lead at ${width}px; disclosures, draft isolation and reading position remain usable`, async ({page}, info) => {
  await page.setViewportSize({width, height: 844})
  let calls = 0
  await page.addInitScript(() => {
    localStorage.setItem('storyforge_guide_completed', 'e2e')
    localStorage.setItem('storyforge-ai-config', JSON.stringify({provider: 'openai', model: 'test', baseUrl: 'https://chat-layout.invalid/v1', apiKey: ''}))
  })
  await page.route('https://chat-layout.invalid/**', async route => {calls++; await route.abort()})
  await page.goto('./chat/library')
  const f = await page.evaluate(async () => {
    const load = new Function('p', 'return import(p)'), api = await load('/storyforge/src/lib/character-interaction/runtime-api.ts')
    const f = await (await load('/storyforge/tests/helpers/chat-narrative-fixture.ts')).seedChatNarrativeRuntimeFixture({maxActionsPerTrigger: 3})
    for (let i = 0; i < 14; i++) {
      const v = await api.readProductRuntimeStateVersion(f.sessionId)
      await api.commitInteractionPlayerMessage({sessionId: f.sessionId, commandId: `layout.${i}`, messageId: `layout.${i}`, baseSequence: v.sequence, baseStateHash: v.stateHash, text: `第 ${i + 1} 条旧对话：雨还没有停，我想先把刚才发生的事情说清楚，不急着替别人作出决定。`, audienceKeys: ['guard', 'player']})
    }
    const v = await api.readProductRuntimeStateVersion(f.sessionId)
    const second = await api.branchProductRuntimeSession({parentSessionId: f.sessionId, throughSequence: v.sequence, title: '另一个故事分支'})
    return {...f, secondId: second.id}
  })
  await page.goto(`./chat/play?project=${f.scope.projectId}&work=${f.scope.workId}&session=${f.sessionId}`)
  const input = page.getByRole('textbox', {name: '发送给角色的消息', exact: true}), picker = page.getByRole('button', {name: '作品与存档'})
  await expect(input).toBeEnabled()
  await expect(picker).toHaveAttribute('aria-expanded', 'false')
  await expect(page.locator('#chat-session-list')).toHaveCount(0)
  await expect(page.getByLabel('演绎节奏', {exact: true})).not.toBeVisible()
  await expect(input).toBeInViewport({ratio: 1})
  await expect(page.getByRole('button', {name: '仅保存消息', exact: true})).toBeInViewport({ratio: 1})
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  const list = page.getByRole('region', {name: '对话记录', exact: true})
  await expect.poll(() => list.evaluate(el => el.scrollHeight - el.clientHeight - el.scrollTop)).toBeLessThan(2)
  await page.screenshot({path: info.outputPath(`chat-first-${width}.png`), fullPage: false})
  await input.fill('留在当前会话的未发送文字')
  await expect(page.getByText('草稿已保存，仅在此存档可见', {exact: true})).toBeVisible()
  await page.reload()
  await expect(input).toHaveValue('留在当前会话的未发送文字')
  await picker.click()
  await page.locator('#chat-session-list').getByRole('button', {name: /另一个故事分支/}).click()
  await expect(input).toHaveValue('')
  await input.fill('属于另一条故事的草稿')
  await picker.click()
  await page.locator('#chat-session-list').getByRole('button', {name: /驿站/}).last().click()
  await expect(input).toHaveValue('留在当前会话的未发送文字')
  await openChatNarrativeTools(page)
  await page.getByLabel('演绎节奏', {exact: true}).selectOption('2')
  await page.getByLabel('角色接续方式', {exact: true}).selectOption('natural')
  await page.getByText('剧情设置与新情境', {exact: true}).click()
  await expect(input).toHaveValue('留在当前会话的未发送文字')
  expect(calls).toBe(0)
  await list.evaluate(el => {el.scrollTop = 0; el.dispatchEvent(new Event('scroll', {bubbles: true}))})
  await page.evaluate(async () => {const load = new Function('p', 'return import(p)'); await (await load('/storyforge/src/stores/character-interaction-player.ts')).useCharacterInteractionPlayerStore.getState().sendPlayerMessage('新到的已保存对话。')})
  await expect(page.getByRole('button', {name: '有新消息，回到底部', exact: true})).toBeVisible()
  expect(await list.evaluate(el => el.scrollTop)).toBe(0)
  await page.getByRole('button', {name: '有新消息，回到底部', exact: true}).click()
  await expect.poll(() => list.evaluate(el => el.scrollHeight - el.clientHeight - el.scrollTop)).toBeLessThan(2)
  await expect(page.getByRole('button', {name: '有新消息，回到底部', exact: true})).toHaveCount(0)
  await input.fill('我的正式新消息')
  await page.getByRole('button', {name: '仅保存消息', exact: true}).click()
  await expect(input).toHaveValue('')
  await expect(list.getByText('我的正式新消息', {exact: true})).toBeVisible()
  await page.reload()
  await expect(list.getByText('我的正式新消息', {exact: true})).toBeVisible()
  await expect(page.getByText('柜台下', {exact: false})).toHaveCount(0)
  expect(calls).toBe(0)
})
