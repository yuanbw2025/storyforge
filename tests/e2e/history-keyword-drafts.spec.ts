import { test, expect } from '@playwright/test'

test('061 independent keyword drafts retain text across select/delete undo/refresh and create only explicitly selected formal rows', async ({ page, context, baseURL }) => {
  const origin = new URL(baseURL!).origin
  let posts = 0
  await context.addInitScript(() => localStorage.setItem('storyforge_guide_completed', 'history061-keyword-drafts'))
  await context.route('**/*', route => {
    const request = route.request(); if (request.method() === 'POST') posts++
    return new URL(request.url()).origin === origin && ['GET','HEAD'].includes(request.method()) ? route.continue() : route.abort()
  })
  await page.goto('./')
  const scope = await page.evaluate(async () => {
    const { seedCurrentWorkspace } = await (new Function('return import("/storyforge/tests/helpers/current-workspace.ts")'))()
    return (await seedCurrentWorkspace('061 独立草稿页面')).scope
  })
  const read = () => page.evaluate(async projectId => {
    const { db } = await (new Function('return import("/storyforge/src/lib/db/schema.ts")'))()
    return db.historicalKeywords.where('projectId').equals(projectId).toArray()
  }, scope.projectId)
  await page.goto(`./workspace/${scope.projectId}?module=history`)
  await page.getByRole('button', { name: '历史细节风暴', exact: true }).click()
  await page.getByRole('button', { name: '整理关键词草稿', exact: true }).click()
  let dialog = page.getByRole('dialog', { name: '关键词草稿', exact: true })
  await expect(dialog.getByRole('button', { name: '添加关键词草稿', exact: true })).toBeVisible()
  await dialog.getByRole('button', { name: '添加关键词草稿', exact: true }).click()
  await dialog.getByRole('textbox', { name: '草稿关键词名称', exact: true }).fill('飞钱')
  await dialog.getByRole('textbox', { name: '草稿条目内容', exact: true }).fill('飞钱的独立原文\n尾空格  ')
  await dialog.getByRole('textbox', { name: '草稿创作方向', exact: true }).fill('希望有市井使用场景。')
  await dialog.getByRole('button', { name: '添加关键词草稿', exact: true }).click()
  await dialog.getByRole('textbox', { name: '草稿关键词名称', exact: true }).fill('盐路')
  await dialog.getByRole('textbox', { name: '草稿条目内容', exact: true }).fill('另一份盐路草稿')
  await dialog.getByRole('button', { name: '飞钱', exact: true }).click()
  await expect(dialog.getByRole('textbox', { name: '草稿条目内容', exact: true })).toHaveValue('飞钱的独立原文\n尾空格  ')
  await dialog.getByRole('checkbox', { name: '选择草稿1：飞钱', exact: true }).check()
  await dialog.getByRole('checkbox', { name: '选择草稿1：飞钱', exact: true }).uncheck()
  await expect(dialog.getByRole('textbox', { name: '草稿条目内容', exact: true })).toHaveValue('飞钱的独立原文\n尾空格  ')
  await dialog.getByRole('button', { name: '删除此草稿', exact: true }).click()
  await dialog.getByText('已删除草稿（可撤销）', { exact: true }).click()
  await dialog.getByRole('button', { name: '撤销删除', exact: true }).click()
  await expect(dialog.getByRole('textbox', { name: '草稿条目内容', exact: true })).toHaveValue('飞钱的独立原文\n尾空格  ')
  await dialog.getByRole('checkbox', { name: '选择草稿1：飞钱', exact: true }).check()
  expect(await read()).toEqual([])
  await dialog.getByRole('button', { name: '关闭关键词草稿', exact: true }).click()
  await page.reload()
  await page.getByRole('button', { name: '历史细节风暴', exact: true }).click()
  await page.getByRole('button', { name: '整理关键词草稿', exact: true }).click()
  dialog = page.getByRole('dialog', { name: '关键词草稿', exact: true })
  await expect(dialog.getByRole('checkbox', { name: '选择草稿1：飞钱', exact: true })).toBeChecked()
  await expect(dialog.getByRole('textbox', { name: '草稿条目内容', exact: true })).toHaveValue('飞钱的独立原文\n尾空格  ')
  await dialog.getByRole('button', { name: '新建所选词条（1）', exact: true }).click()
  await expect(dialog.getByRole('button', { name: '已加入设定，打开正式词条', exact: true })).toBeVisible()
  const rows = await read()
  expect(rows).toHaveLength(1); expect(rows[0]).toMatchObject({ keyword: '飞钱', description: '飞钱的独立原文\n尾空格  ', conceptNote: '希望有市井使用场景。', worldId: scope.worldId })
  expect(rows[0].workId).toBeUndefined()
  await dialog.getByRole('button', { name: '盐路', exact: true }).click()
  await expect(dialog.getByRole('textbox', { name: '草稿条目内容', exact: true })).toHaveValue('另一份盐路草稿')
  await dialog.getByRole('button', { name: '关闭关键词草稿', exact: true }).click()
  expect(posts).toBe(0)
})
