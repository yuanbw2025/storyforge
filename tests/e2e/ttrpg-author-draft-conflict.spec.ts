import { test, expect } from '@playwright/test'
import { readFile } from 'node:fs/promises'

for (const format of ['scripted', 'open'] as const) {
  test(`${format}: two author windows preserve the newer draft and the unsaved local edit`, async ({ page, context }, info) => {
    test.setTimeout(90000)
    test.skip(format === 'open' && process.env.VITE_ENABLE_TTRPG_OPEN_PREVIEW !== '1', 'requires isolated open preview')
    await page.goto('./ttrpg/library')
    await page.getByRole('button', { name: format === 'open' ? '新建开放跑团（预览）' : '新建战役', exact: true }).click()
    await page.getByLabel('战役名称', { exact: true }).fill(`${format} 最初方案`)
    await page.getByRole('button', { name: '保存制作方案', exact: true }).click()
    await expect(page).toHaveURL(/project=/)
    const url = page.url()
    const other = await context.newPage()
    await other.goto(url)
    await expect(other.getByLabel('战役名称', { exact: true })).toHaveValue(`${format} 最初方案`)

    await page.getByLabel('战役名称', { exact: true }).fill(`${format} 本窗口未保存修改`)
    await page.getByRole('textbox', { name: '开场与核心目标', exact: true }).fill('本窗口仍在编辑的开场，不能静默丢弃。')
    await other.getByLabel('战役名称', { exact: true }).fill(`${format} 另一窗口已保存`)
    await other.getByLabel('玩家身份', { exact: true }).fill('另一窗口已确认的调查队身份')
    await other.getByRole('button', { name: '保存制作方案', exact: true }).click()
    await expect(other.getByRole('status').filter({ hasText: '制作配置已保存' })).toBeVisible()
    // Observe the actual Dexie liveQuery update before the old window saves.
    // Its input must retain the old unsaved text while its row sees the new title.
    await expect(page.locator('.lf-heading')).toContainText(`${format} 另一窗口已保存`)
    await expect(page.getByLabel('战役名称', { exact: true })).toHaveValue(`${format} 本窗口未保存修改`)
    const read = async () => page.evaluate(async () => {
      const load = new Function('p', 'return import(p)'), { db } = await load('/storyforge/src/lib/db/schema.ts')
      return { draft: await db.ttrpgAuthoringDrafts.toCollection().first(), work: await db.works.toCollection().first(), builds: await db.productBuilds.count(), runs: await db.agentRuns.count() }
    })
    const before = await read()
    await page.getByRole('button', { name: '保存制作方案', exact: true }).click()
    await expect(page.locator('fieldset.avg-form')).toBeEnabled()
    const after = await read()
    await info.attach('two-window-draft-save', { body: JSON.stringify({ format, before, after }), contentType: 'application/json' })
    expect(after).toEqual(before)
    await expect(page.getByLabel('战役名称', { exact: true })).toHaveValue(`${format} 本窗口未保存修改`)
    await expect(page.getByRole('alert')).toContainText(/其他|另一/)
    await expect(page.getByRole('textbox', { name: '开场与核心目标', exact: true })).toHaveValue('本窗口仍在编辑的开场，不能静默丢弃。')
    expect(after.builds).toBe(0); expect(after.runs).toBe(0)

    // Navigation must use the same original edit basis, rather than saving the
    // stale form with the newer row revision as an implicit side effect.
    await page.getByRole('navigation', { name: '跑团内容导航', exact: true }).getByRole('button', { name: '剧情结构', exact: true }).click()
    await expect(page.getByRole('alert')).toContainText('其他页面修改')
    expect(page.url()).toBe(url)
    expect(await read()).toEqual(before)
    const conflict = page.getByTestId('ttrpg-draft-conflict')
    await expect(conflict).toBeVisible()
    await conflict.screenshot({ path: info.outputPath('draft-conflict-preserves-both-versions.png') })
    if (format === 'open') {
      const editor = page.getByTestId('ttrpg-open-authoring-editor')
      await editor.locator('summary').filter({ hasText: '导入或修改完整开放设计' }).click()
      await editor.getByLabel('开放设计 JSON', { exact: true }).fill('{待完成的原始输入')
      await conflict.getByRole('button', { name: '下载本窗口修改副本', exact: true }).click()
      await expect(page.getByRole('alert')).toContainText('应用或放弃')
      await conflict.getByRole('button', { name: '载入最新方案', exact: true }).click()
      await expect(page.getByRole('alert')).toContainText('应用或放弃')
      await expect(editor.getByLabel('开放设计 JSON', { exact: true })).toHaveValue('{待完成的原始输入')
      expect(await read()).toEqual(before)
      await editor.getByRole('button', { name: '放弃未应用的设计修改', exact: true }).click()
    }
    const downloaded = page.waitForEvent('download')
    await conflict.getByRole('button', { name: '下载本窗口修改副本', exact: true }).click()
    const download = await downloaded, copyPath = info.outputPath('unsaved-authoring-comparison.json')
    await download.saveAs(copyPath)
    const copy = JSON.parse(await readFile(copyPath, 'utf8'))
    expect(copy.scope).toEqual({ projectId: before.draft.projectId, worldId: before.draft.worldId, workId: before.draft.workId })
    expect(copy.baseRevision).toBe(before.draft.revision - 1)
    expect(copy.title).toBe(`${format} 本窗口未保存修改`)
    expect(copy.settings.openingSituation).toBe('本窗口仍在编辑的开场，不能静默丢弃。')
    expect(copy.settings.playerRole).toBe('')
    expect(await read()).toEqual(before)
    await info.attach('unsaved-authoring-comparison', { path: copyPath, contentType: 'application/json' })

    // A cancelled replacement keeps the input; an explicit confirmation loads
    // the actual current Work and draft, without writing either record.
    await conflict.getByRole('button', { name: '载入最新方案', exact: true }).click()
    await page.getByRole('dialog', { name: '载入最新方案？', exact: true }).getByRole('button', { name: '保留本窗口修改', exact: true }).click()
    await expect(page.getByLabel('战役名称', { exact: true })).toHaveValue(`${format} 本窗口未保存修改`)
    await expect(conflict).toBeVisible()
    await conflict.getByRole('button', { name: '载入最新方案', exact: true }).click()
    await page.getByRole('dialog', { name: '载入最新方案？', exact: true }).getByRole('button', { name: '载入最新方案', exact: true }).click()
    await expect(conflict).toHaveCount(0)
    await expect(page.getByLabel('战役名称', { exact: true })).toHaveValue(`${format} 另一窗口已保存`)
    await expect(page.getByLabel('玩家身份', { exact: true })).toHaveValue('另一窗口已确认的调查队身份')
    expect(await read()).toEqual(before)
    await page.getByRole('textbox', { name: '开场与核心目标', exact: true }).fill(copy.settings.openingSituation)
    await page.getByRole('button', { name: '保存制作方案', exact: true }).click()
    await expect(page.getByRole('status').filter({ hasText: '制作配置已保存' })).toBeVisible()
    const merged = await read(), mergedSettings = JSON.parse(merged.draft.settingsJson)
    expect(merged.draft.revision).toBe(before.draft.revision + 1)
    expect(mergedSettings.playerRole).toBe('另一窗口已确认的调查队身份')
    expect(mergedSettings.openingSituation).toBe(copy.settings.openingSituation)
    await page.getByLabel('战役名称', { exact: true }).fill(`${format} 已比对后继续编辑`)
    await page.getByRole('button', { name: '保存制作方案', exact: true }).click()
    await expect(other.getByLabel('战役名称', { exact: true })).toHaveValue(`${format} 已比对后继续编辑`)
    expect((await read()).draft.revision).toBe(before.draft.revision + 2)
    await expect(other.getByRole('textbox', { name: '开场与核心目标', exact: true })).toHaveValue(copy.settings.openingSituation)
    await expect(page.getByRole('alert')).toHaveCount(0)
  })
}

test('browser Back cannot save one Work’s unsaved open design into another scripted Work', async ({ page }, info) => {
  test.skip(process.env.VITE_ENABLE_TTRPG_OPEN_PREVIEW !== '1', 'requires isolated open preview')
  await page.goto('./ttrpg/library')
  await page.getByRole('button', { name: '新建战役', exact: true }).click()
  await page.getByLabel('战役名称', { exact: true }).fill('独立作品甲')
  await page.getByRole('button', { name: '保存制作方案', exact: true }).click()
  await expect(page).toHaveURL(/project=/)
  const firstUrl = page.url()
  await page.getByRole('navigation', { name: '跑团页面导航', exact: true }).getByRole('button', { name: '作品库', exact: true }).click()
  await page.getByRole('button', { name: '新建开放跑团（预览）', exact: true }).click()
  await page.getByLabel('战役名称', { exact: true }).fill('独立开放作品乙')
  await page.getByRole('button', { name: '保存制作方案', exact: true }).click()
  await expect(page).toHaveURL(/project=/)
  const secondWork = Number(new URL(page.url()).searchParams.get('work'))
  const read = async () => page.evaluate(async () => {
    const load = new Function('p', 'return import(p)'), { db } = await load('/storyforge/src/lib/db/schema.ts')
    return { drafts: await db.ttrpgAuthoringDrafts.toArray(), works: await db.works.toArray() }
  })
  const before = await read()
  expect(before.drafts).toHaveLength(2)
  await page.getByLabel('战役名称', { exact: true }).fill('作品乙尚未保存的设计')
  await page.goBack()
  await expect(page).toHaveURL(/\/ttrpg\/library\?/)
  await expect(page.getByTestId('ttrpg-draft-conflict')).toBeVisible()
  await expect(page.getByRole('button', { name: '新建战役', exact: true })).toBeDisabled()
  await expect(page.getByRole('button', { name: '新建开放跑团（预览）', exact: true })).toBeDisabled()
  await page.locator('article').filter({ has: page.getByRole('heading', { name: '独立作品甲', exact: true }) }).getByRole('link', { name: '继续制作', exact: true }).click()
  await expect(page).toHaveURL(firstUrl)
  await page.getByRole('button', { name: '保存制作方案', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('与当前作品不一致')
  expect(await read()).toEqual(before)
  const downloaded = page.waitForEvent('download')
  await page.getByRole('button', { name: '下载本窗口修改副本', exact: true }).click()
  const download = await downloaded, copyPath = info.outputPath('other-work-unsaved-comparison.json')
  await download.saveAs(copyPath)
  const copy = JSON.parse(await readFile(copyPath, 'utf8'))
  expect(copy.scope.workId).toBe(secondWork)
  expect(copy.title).toBe('作品乙尚未保存的设计')
  expect(copy.settings.runFormat).toBe('open')
  await info.attach('preserved-other-work-edit', { path: copyPath, contentType: 'application/json' })
  await page.getByRole('button', { name: '载入最新方案', exact: true }).click()
  await page.getByRole('dialog', { name: '载入最新方案？', exact: true }).getByRole('button', { name: '载入最新方案', exact: true }).click()
  await expect(page.getByLabel('战役名称', { exact: true })).toHaveValue('独立作品甲')
  await expect(page.getByTestId('ttrpg-open-authoring-editor')).toHaveCount(0)
  expect(await read()).toEqual(before)
})
