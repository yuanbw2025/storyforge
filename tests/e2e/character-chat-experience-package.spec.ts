import {expect, test} from '@playwright/test'

for (const width of [390, 1440]) test(`independent browser installs chat packages, retains both versions and resumes the old save at ${width}px`, async ({page, browser}, info) => {
  await page.goto('./chat/library')
  const base = page.url().replace(/chat\/library.*$/, '')
  const packages = await page.evaluate(async () => {
    const load = new Function('p', 'return import(p)')
    return (await load('/storyforge/tests/helpers/chat-experience-package-fixture.ts')).seedChatExperiencePackageFixture({experienceInfo: {version: 1, author: '体验包工程作者', attribution: '工程图片：仅供测试', usageTerms: '测试材料，不提供真实作品许可'}})
  })
  const context = await browser.newContext({viewport: {width, height: 844}})
  try {
    await context.addInitScript(() => {
      localStorage.setItem('storyforge_guide_completed', 'e2e')
      localStorage.setItem('storyforge-ai-config', JSON.stringify({provider: 'openai', model: 'test', baseUrl: 'https://chat-pack.invalid/v1', apiKey: ''}))
    })
    let calls = 0
    for (const pattern of ['**/chat/completions', '**/images/generations', '**/local-codex/v1/requests']) await context.route(pattern, async route => {
      if (route.request().method() === 'POST') {calls++; await route.abort()} else await route.continue()
    })
    const receiver = await context.newPage()
    await receiver.goto(`${base}chat/library`)
    await receiver.getByLabel('作品名称', {exact: true}).fill('独立浏览器的体验包')
    await receiver.getByRole('button', {name: '新建角色聊天', exact: true}).click()
    await expect(receiver).toHaveURL(/chat\/vision\?/)
    const query = new URL(receiver.url()).search
    await receiver.goto(`${base}chat/play${query}`)
    const read = () => receiver.evaluate(async () => {
      const load = new Function('p', 'return import(p)'), {db} = await load('/storyforge/src/lib/db/schema.ts')
      return {worlds: await db.worldReleases.count(), releases: await db.productReleases.toArray(), sessions: await db.productRuntimeSessions.toArray(), events: await db.productRuntimeEvents.toArray(), runs: await db.agentRuns.count()}
    })
    expect((await read()).worlds).toBe(0)
    const panel = receiver.getByLabel('角色聊天体验包', {exact: true})
    await panel.locator('summary').first().click()
    const upload = async (value: unknown) => panel.getByLabel('体验包文件', {exact: true}).setInputFiles({name: '体验.game.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(value))})
    await upload(packages.original)
    await expect(panel.getByRole('button', {name: '确认安装此体验包', exact: true})).toBeVisible()
    const notice = panel.getByRole('region', {name: '体验包安装预览'}).getByLabel('作者与使用说明', {exact: true})
    await notice.locator('summary').click()
    await expect(notice).toContainText('体验包工程作者')
    await expect(notice).toContainText('不提供真实作品许可')
    expect((await read()).releases).toHaveLength(0)
    await panel.getByRole('button', {name: '取消安装', exact: true}).click()
    expect((await read()).releases).toHaveLength(0)
    await upload(packages.original)
    await panel.getByRole('button', {name: '确认安装此体验包', exact: true}).click()
    const originalCard = receiver.getByRole('article', {name: '驿站工程核验 · 版本 1', exact: true})
    await expect(originalCard).toBeVisible()
    await originalCard.getByRole('button', {name: '新建会话', exact: true}).click()
    await receiver.getByLabel('发送给角色的消息', {exact: true}).fill('旧故事：我想先歇一会儿。')
    await receiver.getByRole('button', {name: '仅保存消息', exact: true}).click()
    await expect(receiver.getByRole('region', {name: '对话记录', exact: true})).toContainText('旧故事：我想先歇一会儿。')
    const before = await read()
    await receiver.getByRole('button', {name: '作品与存档', exact: false}).click()
    await panel.locator('summary').first().click()
    await upload(packages.illustrated)
    await panel.getByText('比较本机同标识版本（1）', {exact: true}).click()
    await expect(panel.getByText('本机版本 1 · 内容不同，将并列保留', {exact: true})).toBeVisible()
    await expect(panel.getByRole('region', {name: '体验包安装预览'})).not.toContainText('掌柜把铜印留在柜台下的木箱里。')
    await panel.getByRole('button', {name: '确认安装此体验包', exact: true}).click()
    const newCard = receiver.getByRole('article', {name: '驿站工程核验 · 版本 2', exact: true})
    await expect(newCard).toBeVisible()
    await newCard.getByLabel('作者与使用说明', {exact: true}).locator('summary').click()
    await expect(newCard).toContainText('体验包工程作者')
    const installed = await read()
    expect(installed.sessions).toEqual(before.sessions); expect(installed.events).toEqual(before.events)
    await upload(packages.illustrated)
    await expect(panel.getByText('比较本机同标识版本（2）', {exact: true})).toBeVisible()
    await panel.getByRole('button', {name: '确认安装此体验包', exact: true}).click()
    await expect(panel.getByRole('region', {name: '体验包安装预览'})).toHaveCount(0)
    expect((await read()).releases).toHaveLength(2)
    const newRelease = installed.releases.find((release: {contentHash: string}) => release.contentHash === packages.illustrated.productRelease.contentHash)!
    await panel.getByLabel('导出体验包版本', {exact: true}).selectOption(String(newRelease.id))
    const downloading = receiver.waitForEvent('download')
    await panel.getByRole('button', {name: '导出完整体验包', exact: true}).click()
    const stream = await (await downloading).createReadStream(), chunks: Buffer[] = []
    for await (const chunk of stream) chunks.push(Buffer.from(chunk))
    expect(JSON.parse(Buffer.concat(chunks).toString('utf8'))).toEqual(packages.illustrated)
    await newCard.getByRole('button', {name: '新建会话', exact: true}).click()
    await receiver.getByText('查看画面', {exact: true}).click()
    await expect(receiver.locator('.chat-media-gallery img')).toHaveCount(3)
    await expect(receiver.locator('.chat-media-gallery img').first()).toBeVisible()
    await expect.poll(() => receiver.locator('.chat-media-gallery img').evaluateAll(images => images.every(image => (image as HTMLImageElement).naturalWidth > 0))).toBe(true)
    await receiver.getByRole('button', {name: '作品与存档', exact: false}).click()
    await receiver.locator('#chat-session-list').getByRole('button', {name: /驿站工程核验 · 新会话.*本机版本 1/}).click()
    await expect(receiver.getByRole('region', {name: '对话记录', exact: true})).toContainText('旧故事：我想先歇一会儿。')
    await receiver.reload()
    await expect(receiver.getByRole('region', {name: '对话记录', exact: true})).toContainText('旧故事：我想先歇一会儿。')
    const final = await read()
    expect(final.worlds).toBe(0); expect(final.runs).toBe(0); expect(calls).toBe(0)
    expect(final.sessions).toHaveLength(2)
    expect(final.sessions.find((session: {id: number}) => session.id === before.sessions[0].id)?.productReleaseId).toBe(before.sessions[0].productReleaseId)
    expect(await receiver.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await receiver.screenshot({path: info.outputPath(`chat-package-${width}.png`), fullPage: false})
  } finally {await context.close()}
})
