import { expect, test } from '@playwright/test'
import { createLongform } from './helpers/product-entry'
import { openLongformLeaf } from './helpers/longform-navigation'

test('Unicode 零宽搜索有限返回，错误可修正且 emoji 正常替换刷新保存', async ({ page }) => {
  await page.addInitScript(() => localStorage.setItem('storyforge_guide_completed', 'e2e'))
  let modelRequests = 0
  await page.route('**/chat/completions', async route => { modelRequests += 1; await route.abort() })
  await createLongform(page, 'SFQA088 Unicode 正文')
  await openLongformLeaf(page, '大纲')
  await page.getByRole('button', { name: '添加卷', exact: true }).click()
  await expect.poll(() => page.locator('input').evaluateAll(inputs => inputs.some(input => input instanceof HTMLInputElement && input.value === '第1卷'))).toBe(true)
  await page.getByRole('button', { name: '添加章节', exact: true }).click()
  await expect.poll(() => page.locator('input').evaluateAll(inputs => inputs.some(input => input instanceof HTMLInputElement && input.value === '第1章'))).toBe(true)
  await page.getByTitle('编辑章节').click()
  const editor = page.locator('.tiptap-editor')
  await expect(editor).toBeVisible()
  await editor.fill('😀e\u0301 😀e\u0301')
  await page.getByRole('button', { name: '保存', exact: true }).click()
  await expect(page.getByRole('button', { name: '已保存', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '查找替换', exact: true }).click()
  await page.getByLabel('正则', { exact: true }).check()
  const query = page.getByRole('textbox', { name: '查找', exact: true })
  await query.fill('(?=.)')
  await expect(page.getByText('没有命中。', { exact: true })).toBeVisible()
  await query.fill('[')
  await expect(page.getByRole('button', { name: '查找条件有误 · 0 处', exact: true })).toBeVisible()
  await query.fill('😀')
  await expect(page.getByText('2 处 / 1 章', { exact: true })).toBeVisible()
  await page.getByRole('textbox', { name: '替换为', exact: true }).fill('🌍')
  await page.getByRole('button', { name: '替换单处', exact: true }).click()
  const confirmation = page.locator('div.fixed.inset-0').filter({ hasText: '确认替换？' })
  await confirmation.getByRole('button', { name: '创建快照并替换', exact: true }).click()
  await expect(editor).toContainText('🌍e\u0301 😀e\u0301')
  await page.reload()
  await openLongformLeaf(page, '章节')
  await expect(editor).toContainText('🌍e\u0301 😀e\u0301')
  expect(modelRequests).toBe(0)
})
