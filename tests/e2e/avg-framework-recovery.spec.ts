import { test,expect } from '@playwright/test'

test('a real authored AVG preview checkpoint fork and subsequent save selection survive immediate refresh at their exact session',async({page})=>{
  test.setTimeout(90_000)
  await page.addInitScript(()=>localStorage.setItem('storyforge_guide_completed','e2e'))
  await page.goto('./avg/library')
  await expect(page.getByRole('button',{name:'新建 AVG',exact:true})).toBeVisible({timeout:30_000})
  const s=await page.evaluate(async()=>{const load=new Function('p','return import(p)') as(p:string)=>Promise<any>;return(await load('/storyforge/tests/helpers/avg-release-fixture.ts')).prepareAvgMediaReleasePreview()})
  await page.goto(`./avg/play?project=${s.scope.projectId}&work=${s.scope.workId}&session=${s.sessionId}`)
  await expect(page.locator('.avg-text-cursor')).toHaveClass(/is-complete/)
  await page.context().setOffline(true)
  await page.getByRole('button',{name:'快速存档',exact:true}).click()
  await expect(page.getByRole('status').filter({hasText:'已快速存档'})).toBeVisible()
  const retry=page.getByRole('button',{name:'重试配音',exact:true});if(await retry.isVisible())await retry.click()
  await expect.poll(()=>page.evaluate(async id=>{const load=new Function('p','return import(p)') as(p:string)=>Promise<any>;return(await(await load('/storyforge/src/lib/product/runtime-core.ts')).readProductRuntimeState(id)).avgReading.current.status},s.sessionId)).toBe('ended')
  await page.getByRole('button',{name:'继续',exact:true}).click();await page.getByRole('button',{name:'打开灯光',exact:true}).click()
  await expect(page.locator('.avg-dialogue p')).toContainText('灯光亮起')
  await page.getByRole('button',{name:'存读档',exact:true}).click()
  const saves=page.getByRole('dialog',{name:'存读档'})
  await saves.getByRole('article').filter({hasText:'快速存档'}).getByRole('button',{name:'从这里开始新分支',exact:true}).click()
  await expect(saves).not.toBeVisible()
  await expect(page.locator('.avg-dialogue p')).toContainText('这是原创工程校准文本')
  const childId=await page.evaluate(async()=>{const load=new Function('p','return import(p)') as(p:string)=>Promise<any>;return(await load('/storyforge/src/stores/avg-game-player.ts')).useAvgGamePlayerStore.getState().selectedSessionId})
  expect(childId).not.toBe(s.sessionId)
  await expect.poll(()=>Number(new URL(page.url()).searchParams.get('session'))).toBe(childId)
  await page.context().setOffline(false)
  await page.reload()
  await expect(page.locator('.avg-dialogue p')).toContainText('这是原创工程校准文本')
  await expect.poll(()=>page.locator('.avg-background img').evaluate((image:HTMLImageElement)=>image.complete?image.naturalWidth:0)).toBe(960)
  await page.getByRole('button',{name:'存读档',exact:true}).click()
  await saves.getByRole('button',{name:'读取',exact:true}).click()
  await expect.poll(()=>Number(new URL(page.url()).searchParams.get('session'))).toBe(s.sessionId)
  await page.reload();await expect(page.locator('.avg-dialogue p')).toContainText('灯光亮起')
  await page.getByRole('button',{name:'存读档',exact:true}).click()
  await saves.getByRole('button',{name:'删除当前存档',exact:true}).click()
  await page.getByRole('dialog',{name:'删除当前 AVG 存档？',exact:true}).getByRole('button',{name:'删除存档',exact:true}).click()
  await expect(page.getByRole('heading',{name:'AVG 游戏库',exact:true})).toBeVisible()
  await expect.poll(()=>new URL(page.url()).searchParams.get('session')).toBeNull()
  const preserved=await page.evaluate(async ids=>{
    const load=new Function('p','return import(p)') as(p:string)=>Promise<any>,{db}=await load('/storyforge/src/lib/db/schema.ts')
    return {original:await db.productRuntimeSessions.get(ids.original)??null,child:await db.productRuntimeSessions.get(ids.child)}
  },{original:s.sessionId,child:childId})
  expect(preserved.original).toBeNull();expect(preserved.child.parentSessionId).toBeNull()
  expect(preserved.child.productBuildId).toBe(s.buildId)
  await page.reload();await expect(page.locator('.avg-dialogue')).toHaveCount(0)
  await page.locator('.avg-title-sessions button').click()
  await expect(page.locator('.avg-dialogue p')).toContainText('这是原创工程校准文本')
  await expect.poll(()=>Number(new URL(page.url()).searchParams.get('session'))).toBe(childId)
})
