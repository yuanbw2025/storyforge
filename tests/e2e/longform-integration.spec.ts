  const primary = page.getByRole('navigation', { name: '长篇一级导航' })
  await primary.getByRole('button', { name: '版本与导出', exact: true }).click()
  await page.getByRole('navigation', { name: '版本与导出', exact: true }).getByRole('button', { name: '导出与备份', exact: true }).click()
  await expect(page).toHaveURL(/module=export/)
  await primary.getByRole('button', { name: '派生世界', exact: true }).click()
  await expect(page.getByRole('button', { name: '派生世界草稿', exact: true })).toBeVisible()
