import {expect, test} from '@playwright/test'

for (const width of [390, 1440]) test(`a compatible chat save upgrades by explicit copy and returns to the original at ${width}px`, async ({page}, info) => {
  await page.setViewportSize({width, height: 844})
  await page.addInitScript(() => {
    localStorage.setItem('storyforge_guide_completed', 'e2e')
    localStorage.setItem('storyforge-ai-config', JSON.stringify({provider: 'openai', model: 'test', baseUrl: 'https://chat-upgrade.invalid/v1', apiKey: ''}))
  })
  let modelCalls = 0
  for (const pattern of ['**/chat/completions', '**/images/generations', '**/local-codex/v1/requests']) await page.route(pattern, async route => {
    if (route.request().method() === 'POST') {modelCalls++; await route.abort()} else await route.continue()
  })
  await page.goto('./chat/library')
  const f = await page.evaluate(async () => {
    const load = new Function('p', 'return import(p)'), packages = await (await load('/storyforge/tests/helpers/chat-experience-package-fixture.ts')).seedChatExperiencePackageFixture()
    const target = await (await load('/storyforge/src/lib/character-interaction/draft-service.ts')).createChatDraftV3('升级界面工程核验')
    const {previewChatExperiencePackageV1, installChatExperiencePackageV1} = await load('/storyforge/src/lib/character-interaction/experience-package.ts')
    const install = async (bundle: unknown) => installChatExperiencePackageV1(await previewChatExperiencePackageV1({scope: target.scope, bytes: new TextEncoder().encode(JSON.stringify(bundle)).buffer}))
    const original = await install(packages.original), next = await install(packages.illustrated)
    const store = (await load('/storyforge/src/stores/character-interaction-player.ts')).useCharacterInteractionPlayerStore
    await store.getState().load(target.scope, null)
    const parentSessionId = await store.getState().start(original.id, '雨夜原存档')
    await store.getState().sendPlayerMessage('旧故事：我先在驿站休息。')
    return {scope: target.scope, parentSessionId, targetReleaseId: next.id}
  })
  const rows = () => page.evaluate(async projectId => {
    const {db} = await (new Function('p', 'return import(p)'))('/storyforge/src/lib/db/schema.ts')
    return {sessions: await db.productRuntimeSessions.where('projectId').equals(projectId).toArray(),
      events: await db.productRuntimeEvents.where('projectId').equals(projectId).toArray(), runs: await db.agentRuns.where('projectId').equals(projectId).count()}
  }, f.scope.projectId)
  await page.goto(`./chat/play?project=${f.scope.projectId}&work=${f.scope.workId}&session=${f.parentSessionId}`)
  const messages = page.getByRole('region', {name: '对话记录', exact: true}), composer = page.getByLabel('发送给角色的消息', {exact: true})
  await expect(messages).toContainText('旧故事：我先在驿站休息。')
  await composer.fill('留在原存档的未发送文字')
  await expect.poll(async () => (await rows()).sessions[0]?.chatComposerDraft?.text).toBe('留在原存档的未发送文字')
  const before = await rows()
  await page.getByRole('button', {name: '作品与存档'}).click()
  const upgrade = page.getByLabel('存档版本升级', {exact: true})
  await upgrade.locator('summary').click()
  await upgrade.getByLabel('升级目标版本', {exact: true}).selectOption(String(f.targetReleaseId))
  await upgrade.getByRole('button', {name: '检查存档兼容性', exact: true}).click()
  await expect(upgrade.getByRole('button', {name: '确认创建升级副本', exact: true})).toBeVisible()
  expect((await rows()).sessions).toEqual(before.sessions)
  await upgrade.getByRole('button', {name: '取消升级', exact: true}).click()
  expect((await rows()).sessions).toHaveLength(1)
  await upgrade.getByRole('button', {name: '检查存档兼容性', exact: true}).click()
  await upgrade.getByRole('button', {name: '确认创建升级副本', exact: true}).click()
  await expect.poll(async () => (await rows()).sessions.length).toBe(2)
  const copied = await rows(), child = copied.sessions.find((session: {id: number}) => session.id !== f.parentSessionId)!
  await expect(page).toHaveURL(new RegExp(`session=${child.id}(?:&|$)`))
  await expect(messages).toContainText('旧故事：我先在驿站休息。')
  await expect(composer).toHaveValue('')
  expect(copied.sessions.find((session: {id: number}) => session.id === f.parentSessionId)).toEqual(before.sessions[0])
  expect(copied.events.filter((event: {sessionId: number}) => event.sessionId === f.parentSessionId)).toEqual(before.events)
  expect(copied.events.filter((event: {sessionId: number}) => event.sessionId === child.id).map((event: {type: string}) => event.type)).toEqual(['interaction.release.upgraded'])
  await page.getByText('查看画面', {exact: true}).click()
  await expect(page.locator('.chat-media-gallery img')).toHaveCount(3)
  await expect.poll(() => page.locator('.chat-media-gallery img').evaluateAll(images => images.every(image => (image as HTMLImageElement).naturalWidth > 0))).toBe(true)
  await page.getByText('查看画面', {exact: true}).click()
  await composer.fill('副本里的新故事：我现在去看门边的告示。')
  await page.getByRole('button', {name: '仅保存消息', exact: true}).click()
  await expect(messages).toContainText('副本里的新故事')
  await page.reload()
  await expect(messages).toContainText('副本里的新故事')
  await page.getByRole('button', {name: '作品与存档'}).click()
  await upgrade.locator('summary').click()
  await upgrade.getByRole('button', {name: '返回原存档', exact: true}).click()
  await expect(page).toHaveURL(new RegExp(`session=${f.parentSessionId}(?:&|$)`))
  await expect(messages).toContainText('旧故事：我先在驿站休息。')
  await expect(messages).not.toContainText('副本里的新故事')
  await expect(composer).toHaveValue('留在原存档的未发送文字')
  const final = await rows()
  expect(final.events.filter((event: {sessionId: number}) => event.sessionId === f.parentSessionId)).toEqual(before.events)
  expect(final.runs).toBe(0); expect(modelCalls).toBe(0)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({path: info.outputPath(`chat-upgrade-${width}.png`), fullPage: false})
})
