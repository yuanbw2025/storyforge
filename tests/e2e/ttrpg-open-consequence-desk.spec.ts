import { expect, test } from '@playwright/test'
test.beforeEach(() => { test.skip(process.env.VITE_ENABLE_TTRPG_OPEN_PREVIEW !== '1', 'requires isolated preview') })
test('a host explicitly reviews pressure parameters and returns to personal consent before payment', async ({ page }) => {
  await page.goto('./')
  const f = await page.evaluate(async () => {
    const importer = new Function('p', 'return import(p)') as (p: string) => Promise<any>
    const h = await importer('/storyforge/tests/helpers/open-ttrpg-pressure-effect.ts'), a = await importer('/storyforge/src/lib/ttrpg/runtime-api.ts')
    const f = await h.setupPressureEffectFixtureV1({}, (pkg: any) => { pkg.ttrpg.campaign.effectPlanTemplates[0].reason = 'HOST-ONLY-PRESSURE-REASON' })
    const state = await a.readProductRuntimeState(f.command.sessionId)
    return { sessionId: f.command.sessionId, viewerKey: f.command.viewerKey, resource: f.resource, resourceName: f.f.runtimePackage.ttrpg.rulePack.content.resources[0].name, before: Number(state.entities.hero.attributes[`resource.${f.resource}`]), worldTime: state.ttrpg.openRun.worldTime }
  })
  await page.goto(`./play/session/${f.sessionId}`)
  await page.getByLabel('我的角色', { exact: true }).selectOption(f.viewerKey)
  await page.getByRole('button', { name: '确认身份并进入', exact: true }).click()
  await expect(page.locator('body')).not.toContainText('HOST-ONLY-PRESSURE-REASON')
  await expect(page.getByRole('button', { name: '进入后果参数审查', exact: true })).toBeDisabled()
  await page.getByLabel('我正在以主持身份审查，可以查看未公开资料。', { exact: true }).check()
  await page.getByRole('button', { name: '进入后果参数审查', exact: true }).click()
  await expect(page.getByRole('group', { name: '主持后果参数', exact: true })).toContainText('HOST-ONLY-PRESSURE-REASON')
  await expect(page.getByRole('button', { name: '检查具体后果', exact: true })).toBeDisabled()
  await page.getByLabel('后果对象 1', { exact: true }).selectOption('hero')
  await page.getByLabel('后果方案', { exact: true }).selectOption('large')
  await page.getByRole('button', { name: '检查具体后果', exact: true }).click()
  await expect(page.getByRole('region', { name: '主持后果预览', exact: true })).toContainText('消耗 2')
  await expect(page.getByRole('region', { name: '我的当前状态', exact: true })).toContainText(`${f.resourceName}：${f.before}`)
  await page.screenshot({ path: test.info().outputPath('p3-consequence-host-browser.png'), fullPage: true })
  await page.getByRole('button', { name: '确认主持裁定并提交相关玩家', exact: true }).click()
  await expect(page.locator('body')).not.toContainText('HOST-ONLY-PRESSURE-REASON')
  await expect(page.getByRole('button', { name: '接受该角色的后果', exact: true })).toBeVisible()
  await expect(page.getByRole('region', { name: '我的当前状态', exact: true })).toContainText(`${f.resourceName}：${f.before}`)
  await page.getByRole('button', { name: '接受该角色的后果', exact: true }).click()
  await page.getByRole('button', { name: '继续结算已确认的行动', exact: true }).click()
  await expect(page.getByRole('region', { name: '我的当前状态', exact: true })).toContainText(`${f.resourceName}：${f.before - 2}`)
  await page.reload()
  await page.getByLabel('我的角色', { exact: true }).selectOption(f.viewerKey)
  await page.getByRole('button', { name: '确认身份并进入', exact: true }).click()
  await expect(page.getByRole('region', { name: '我的当前状态', exact: true })).toContainText(`${f.resourceName}：${f.before - 2}`)
  await expect(page.locator('body')).not.toContainText('HOST-ONLY-PRESSURE-REASON')
  const state = await page.evaluate(async sessionId => {
    const importer = new Function('p', 'return import(p)') as (p: string) => Promise<any>
    return (await importer('/storyforge/src/lib/ttrpg/runtime-api.ts')).readProductRuntimeState(sessionId)
  }, f.sessionId)
  expect(state.ttrpg.openRun.worldTime).toEqual(f.worldTime)
  expect(state.ttrpg.openRun.coordination.calls).toEqual([])
})
test('the host closes a legitimate stage with a private summary and settles without extra world time', async ({ page }) => {
  await page.goto('./')
  const f = await page.evaluate(async () => {
    const importer = new Function('p', 'return import(p)') as (p: string) => Promise<any>
    const h = await importer('/storyforge/tests/helpers/open-ttrpg-checks.ts'), a = await importer('/storyforge/src/lib/ttrpg/runtime-api.ts')
    const f = await h.setupChecksFixtureV1({ closure: true })
    await a.resumeTtrpgOpenChecksV1(f.command)
    return { sessionId: f.command.sessionId, viewerKey: f.command.viewerKey, worldTime: (await a.readProductRuntimeState(f.command.sessionId)).ttrpg.openRun.worldTime }
  })
  await page.goto(`./play/session/${f.sessionId}`)
  await page.getByLabel('我的角色', { exact: true }).selectOption(f.viewerKey)
  await page.getByRole('button', { name: '确认身份并进入', exact: true }).click()
  await page.getByLabel('我正在以主持身份审查，可以查看未公开资料。', { exact: true }).check()
  await page.getByRole('button', { name: '审查阶段收束条件', exact: true }).click()
  await page.getByLabel('主持私密阶段记录', { exact: true }).fill('HOST-ONLY-STAGE-SUMMARY')
  await page.getByRole('button', { name: '确认收束当前阶段', exact: true }).click()
  await expect(page.locator('body')).toContainText('本阶段已明确收束')
  await expect(page.getByLabel('主持私密阶段记录', { exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: '继续结算已确认的行动', exact: true }).click()
  await expect(page.getByText('改由真人主持补写叙述', { exact: true })).toBeVisible()
  await page.reload()
  await page.getByLabel('我的角色', { exact: true }).selectOption(f.viewerKey)
  await page.getByRole('button', { name: '确认身份并进入', exact: true }).click()
  await expect(page.locator('body')).not.toContainText('HOST-ONLY-STAGE-SUMMARY')
  const state = await page.evaluate(async sessionId => {
    const importer = new Function('p', 'return import(p)') as (p: string) => Promise<any>
    return (await importer('/storyforge/src/lib/ttrpg/runtime-api.ts')).readProductRuntimeState(sessionId)
  }, f.sessionId)
  expect(state.ttrpg.openRun.stage.status).toBe('closed')
  expect(state.ttrpg.openRun.stageClosures).toHaveLength(1)
  expect(state.ttrpg.openRun.stageClosures[0].summary).toEqual({ text: 'HOST-ONLY-STAGE-SUMMARY', audience: 'gm-only' })
  expect(state.ttrpg.openRun.worldTime).toEqual(f.worldTime)
  expect(state.ttrpg.openRun.coordination.calls).toEqual([])
})
