import {test, expect} from '@playwright/test'

test('author grants, reviews and revokes world-fact discovery without losing unrelated classifications or exposing the truth to the role', async ({page}) => {
  await page.addInitScript(() => localStorage.setItem('storyforge_guide_completed', 'e2e'))
  let calls = 0
  await page.route('**/chat/completions', async route => {calls++; await route.abort()})
  await page.goto('./chat/library')
  const f = await page.evaluate(async () => {
    const load = new Function('p', 'return import(p)')
    const f = await (await load('/storyforge/tests/helpers/chat-narrative-production-fixture.ts')).seedChatNarrativeProductionFixture({worldDiscovery: true})
    return {scope: f.scope, worldReleaseId: f.confirmed.worldReleaseId, sourceHash: f.source.source.knowledge.find((s: {discovery?: unknown}) => s.discovery).source.sourceHash}
  })
  const query = `project=${f.scope.projectId}&work=${f.scope.workId}`
  const open = async () => {
    await page.goto(`./chat/cast?${query}`)
    await page.getByRole('button', {name: '读取并检查完整资料', exact: true}).click()
  }
  const secret = page.getByTestId('chat-source-fragment').filter({has: page.locator('pre').filter({hasText: '红铜钥匙藏在修钟台下的木匣里。'})})
  const save = async () => {
    await page.getByRole('button', {name: '确认可见范围并用于新制作', exact: true}).click()
    await expect(secret).toHaveCount(0)
  }
  await open()
  await expect(secret).toHaveCount(1)
  await secret.getByRole('combobox', {name: /可见范围$/}).selectOption('author-only')
  await expect(secret.getByTestId('chat-source-discovery')).toHaveCount(0)
  await save()
  await open()
  await expect(secret.getByRole('combobox', {name: /可见范围$/})).toHaveValue('author-only')
  await secret.getByRole('combobox', {name: /可见范围$/}).selectOption('discoverable')
  const confirm = page.getByRole('button', {name: '确认可见范围并用于新制作', exact: true})
  await expect(confirm).toBeDisabled()
  await secret.getByRole('textbox', {name: /发现条件$/}).fill('店主实际打开并查看修钟台下木匣的内部；仅查看外观不足以发现。')
  await expect(confirm).toBeDisabled()
  await secret.getByRole('checkbox', {name: /修钟台下有一只获准由店主检查的木匣/}).check()
  const investigators = secret.getByRole('group', {name: '允许调查的角色', exact: true})
  await investigators.getByRole('checkbox', {name: '林舟', exact: true}).uncheck()
  await expect(confirm).toBeDisabled()
  await investigators.getByRole('checkbox', {name: '林舟', exact: true}).check()
  await expect(confirm).toBeEnabled()
  // Changing a selected prerequisite must leave the invalid choice removable.
  const prerequisite = page.getByTestId('chat-source-fragment').filter({has: page.locator('pre').filter({hasText: '修钟台下有一只获准由店主检查的木匣。'})})
  const prerequisiteChoice = secret.getByRole('checkbox', {name: /修钟台下有一只获准由店主检查的木匣/})
  const invalidChoice = secret.getByText('此项已不满足前提要求；请取消选择或修改对应资料。', {exact: true})
  await prerequisite.getByRole('combobox', {name: /可见范围$/}).selectOption('author-only')
  await expect(confirm).toBeDisabled()
  await expect(prerequisiteChoice).toBeChecked()
  await expect(invalidChoice).toBeVisible()
  await prerequisite.getByRole('combobox', {name: /可见范围$/}).selectOption('public')
  await expect(confirm).toBeEnabled()
  await expect(invalidChoice).toHaveCount(0)
  await prerequisite.getByRole('combobox', {name: /用途$/}).selectOption('identity')
  await expect(confirm).toBeDisabled()
  await expect(prerequisiteChoice).toBeChecked()
  await expect(invalidChoice).toBeVisible()
  // The invalid option disappears on deselection; assert that outcome directly.
  await prerequisiteChoice.click()
  await expect(prerequisiteChoice).toHaveCount(0)
  await expect(confirm).toBeDisabled()
  await expect(secret.getByRole('textbox', {name: /发现条件$/})).toHaveValue('店主实际打开并查看修钟台下木匣的内部；仅查看外观不足以发现。')
  await expect(investigators.getByRole('checkbox', {name: '林舟', exact: true})).toBeChecked()
  await prerequisite.getByRole('combobox', {name: /用途$/}).selectOption('knowledge')
  await expect(prerequisiteChoice).not.toBeChecked()
  await prerequisiteChoice.check()
  await expect(confirm).toBeEnabled()
  await page.setViewportSize({width: 390, height: 844})
  expect(await page.evaluate(() => document.documentElement.scrollWidth - innerWidth)).toBeLessThanOrEqual(1)
  await save()
  await page.reload()
  await open()
  await expect(secret.getByRole('textbox', {name: /发现条件$/})).toHaveValue('店主实际打开并查看修钟台下木匣的内部；仅查看外观不足以发现。')
  await expect(secret.getByRole('checkbox', {name: /修钟台下有一只获准由店主检查的木匣/})).toBeChecked()
  const compiled = await page.evaluate(async f => {
    const load = new Function('p', 'return import(p)')
    const draft = await (await load('/storyforge/src/lib/character-interaction/draft-service.ts')).readChatDraftV1(f.scope), settings = JSON.parse(draft.settingsJson)
    const consultation = await load('/storyforge/src/lib/product-production/consultation.ts')
    const starting = await consultation.suggestProductStartingPoints({scope: f.scope, worldReleaseId: f.worldReleaseId})
    const brief = await consultation.draftProductProductionBriefV3({scope: f.scope, worldReleaseId: f.worldReleaseId, suggestionKey: starting.suggestions[0].suggestionKey, productType: 'character-interaction', characterChat: settings, playerRole: settings.playerRole, openingSituation: settings.openingSituation, visualLevel: 'none', audioLevel: 'none'})
    const sourceCatalog = await (await load('/storyforge/src/lib/product-production/world-source.ts')).loadProductProductionWorldSourceCatalogV2({scope: f.scope, worldReleaseId: f.worldReleaseId, selection: brief.source.selection})
    const compiler = await load('/storyforge/src/lib/product-production/product-module-compilers.ts'), projected = compiler.prepareChatNarrativeCompilerSourceV1({brief, sourceCatalog})
    const source = {schema: 'storyforge.chat-narrative-production-source', version: 1, settings, source: projected.content, participants: projected.participantKeys.map((participantKey: string, i: number) => ({participantKey, characterKey: projected.characterKeys[i], name: projected.names[i], voiceRules: projected.voices[i] || '自然表达'}))}
    const candidates = (await load('/storyforge/tests/helpers/chat-narrative-production-fixture.ts')).chatSituationCandidatesFixture(source)
    const production = await load('/storyforge/src/lib/character-interaction/narrative-production.ts'), hash = (await load('/storyforge/src/lib/product-production/hash.ts')).hashProductProductionValueV2
    const content = await production.selectChatNarrativeCandidateV1({source, candidates, selection: {schema: 'storyforge.chat-situation-selection', version: 1, candidatesHash: await hash(candidates), sourceHash: await hash(source), selectedOptionKey: 'option-1', authorCommandId: 'ui.author.select'}})
    const frozen = compiler.compileInteractionModulesV1({brief, sourceCatalog, narrative: production.chatNarrativeShellV1(content), chatNarrative: content}), runtime = await load('/storyforge/src/lib/character-interaction/runtime.ts')
    const state = runtime.createInitialInteractionState(frozen)
    return {source: projected.content, role: runtime.interactionVisibilityView(state, projected.participantKeys[0]), player: runtime.interactionVisibilityView(state, 'player')}
  }, f)
  expect(compiled.source.version).toBe(4)
  expect(compiled.source.knowledge.find((s: {discovery?: unknown}) => s.discovery)).toMatchObject({audienceKeys: [], source: {sourceHash: f.sourceHash}})
  expect(JSON.stringify(compiled.role)).not.toContain('红铜钥匙')
  expect(JSON.stringify(compiled.player)).not.toContain('红铜钥匙')
  await page.goto(`./chat/vision?${query}`)
  await expect(page.getByLabel('允许角色依据未完成事项发展新局面', {exact: true})).toBeDisabled()
  expect(await page.getByLabel('每次调查最多揭示', {exact: true}).locator('option[value="0"]').evaluate((e: HTMLOptionElement) => e.disabled)).toBe(true)
  await open()
  // Author explicitly cancels the grant; the public prerequisite is retained.
  await secret.getByRole('combobox', {name: /可见范围$/}).selectOption('participants')
  const holders = secret.getByTestId('chat-initial-audience')
  await holders.getByRole('checkbox', {name: '玩家', exact: true}).check()
  await holders.getByRole('checkbox', {name: '林舟', exact: true}).uncheck()
  await investigators.getByRole('checkbox', {name: '林舟', exact: true}).check()
  await save()
  await open()
  await expect(holders.getByRole('checkbox', {name: '玩家', exact: true})).toBeChecked()
  await expect(holders.getByRole('checkbox', {name: '林舟', exact: true})).not.toBeChecked()
  await expect(investigators.getByRole('checkbox', {name: '林舟', exact: true})).toBeChecked()
  await secret.getByLabel('允许其他角色调查发现', {exact: true}).uncheck()
  await expect(secret.getByTestId('chat-source-discovery')).toHaveCount(0)
  await save()
  const revoked = await page.evaluate(async f => {
    const load = new Function('p', 'return import(p)'), draft = await (await load('/storyforge/src/lib/character-interaction/draft-service.ts')).readChatDraftV1(f.scope)
    return JSON.parse(draft.settingsJson).sourceReview.classifications
  }, f)
  expect(revoked.some((row: {discovery?: unknown}) => row.discovery)).toBe(false)
  expect(revoked.find((row: {fragmentKey: string}) => row.fragmentKey.endsWith('#/shortDescription'))).toMatchObject({visibility: 'public', purpose: 'knowledge'})
  await page.goto(`./chat/vision?${query}`)
  await page.getByLabel('每次调查最多揭示', {exact: true}).selectOption('0')
  await page.getByRole('button', {name: '保存方案', exact: true}).click()
  await expect(page.getByText('方案已保存', {exact: true})).toBeVisible()
  await page.reload()
  await expect(page.getByLabel('每次调查最多揭示', {exact: true})).toHaveValue('0')
  expect(calls).toBe(0)
})
