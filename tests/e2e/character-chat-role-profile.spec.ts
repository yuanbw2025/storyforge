import {test, expect} from '@playwright/test'

test('author edits a cited role interpretation, sees it in the correct actor runtime input and repairs stale permissions', async ({page}) => {
  let modelCalls = 0
  page.on('request', request => {if (request.method() === 'POST' && /chat\/completions|local-codex\/v1\/requests/.test(request.url())) modelCalls++})
  await page.addInitScript(() => localStorage.setItem('storyforge_guide_completed', 'e2e'))
  await page.goto('./chat/library')
  const f = await page.evaluate(async () => {
    const load = new Function('p', 'return import(p)'), helper = await load('/storyforge/tests/helpers/chat-role-profile.ts')
    const f = await helper.seedChatRoleProfileFixture()
    return {scope: f.scope, actorKey: f.actor.resourceKey, settingsJson: f.draft.settingsJson, worldHash: f.world.release.contentHash}
  })
  await page.goto(`./chat/cast?project=${f.scope.projectId}&work=${f.scope.workId}`)
  const read = page.getByRole('button', {name: '读取并检查完整资料', exact: true})
  await read.click()
  const source = page.getByTestId('chat-source-fragment').filter({has: page.locator('pre').filter({hasText: '谨慎而固执'})})
  await source.getByRole('checkbox', {name: /加入整理建议$/}).check()
  await page.getByRole('combobox', {name: '整理人物', exact: true}).selectOption({label: '林舟'})
  await page.getByRole('button', {name: '手工整理所选原文', exact: true}).click()
  const content = page.getByRole('textbox', {name: '特征 1 内容', exact: true})
  await content.fill('做判断时保持谨慎；立场不会轻易改变。')
  await page.getByRole('combobox', {name: '特征 1 依据 1 来源', exact: true}).selectOption({index: 1})
  const quote = page.getByRole('textbox', {name: '特征 1 依据 1 引用', exact: true})
  await quote.fill('没有出现过的原句')
  const save = page.getByRole('button', {name: '确认人物整理并用于新制作', exact: true})
  await save.click()
  await expect(page.getByRole('alert').filter({hasText: '引用必须来自对应原文'})).toBeVisible()
  expect(await page.evaluate(async scope => {
    const load = new Function('p', 'return import(p)'), {db} = await load('/storyforge/src/lib/db/schema.ts')
    return (await db.chatAuthoringDrafts.where('workId').equals(scope.workId).first()).roleProfilesJson
  }, f.scope)).toBeUndefined()
  await quote.fill('谨慎而固执'); await save.click()
  await expect(page.getByTestId('chat-role-trait-editor')).toHaveCount(0)
  await read.click()
  await expect(page.getByTestId('chat-role-profile')).toContainText('做判断时保持谨慎')
  const compiled = await page.evaluate(async f => {
    const load = new Function('p', 'return import(p)'), helper = await load('/storyforge/tests/helpers/chat-role-profile.ts'), compiler = await load('/storyforge/src/lib/product-production/product-module-compilers.ts'), {db} = await load('/storyforge/src/lib/db/schema.ts')
    const input = await helper.chatRoleProfileCompilerInput(f.scope), result = compiler.compileInteractionModulesV1(input)
    return {profiles: result.profiles, source: result.chatSource, draft: await db.chatAuthoringDrafts.where('workId').equals(f.scope.workId).first(), worldHashes: (await db.worldReleases.toArray()).map(row => row.contentHash)}
  }, f)
  expect(compiled.profiles.find((row: {characterKey: string}) => row.characterKey === f.actorKey).voiceRules).toContain('做判断时保持谨慎')
  for (const other of compiled.profiles.filter((row: {characterKey: string}) => row.characterKey !== f.actorKey)) expect(other.voiceRules).not.toContain('做判断时保持谨慎')
  expect(JSON.stringify(compiled.source)).not.toContain('做判断时保持谨慎')
  expect(compiled.draft.settingsJson).toBe(f.settingsJson)
  expect(compiled.worldHashes.every((hash: string) => hash === f.worldHash)).toBe(true)
  await page.reload(); await read.click()
  await page.getByRole('button', {name: '编辑并重新确认林舟的整理', exact: true}).click()
  await expect(content).toHaveValue('做判断时保持谨慎；立场不会轻易改变。')
  await content.fill('面对没有把握的情况先核实，已有立场不会轻易改变。')
  await save.click(); await expect(page.getByTestId('chat-role-trait-editor')).toHaveCount(0); await read.click()
  const visibility = source.getByRole('combobox', {name: /可见范围$/})
  await visibility.selectOption('author-only')
  await page.getByRole('button', {name: '确认可见范围并用于新制作', exact: true}).click(); await read.click()
  await expect(page.getByTestId('chat-role-profile')).toContainText('新制作暂不能使用这份整理')
  await page.getByRole('button', {name: '编辑并重新确认林舟的整理', exact: true}).click()
  await expect(page.getByRole('alert').filter({hasText: '尚未获准知道'})).toBeVisible()
  await visibility.selectOption('public')
  await page.getByRole('button', {name: '确认可见范围并用于新制作', exact: true}).click(); await read.click()
  await expect(page.getByTestId('chat-role-profile')).toContainText('新制作暂不能使用这份整理')
  await page.getByRole('button', {name: '编辑并重新确认林舟的整理', exact: true}).click()
  await save.click(); await expect(page.getByTestId('chat-role-trait-editor')).toHaveCount(0); await read.click()
  await expect(page.getByTestId('chat-role-profile')).not.toContainText('新制作暂不能使用这份整理')
  await page.setViewportSize({width: 390, height: 844})
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.getByRole('button', {name: '移除林舟的整理', exact: true}).click(); await read.click()
  await expect(page.getByTestId('chat-role-profile')).toHaveCount(0)
  expect(modelCalls).toBe(0)
})
