import {test, expect} from '@playwright/test'

test('author creates chat-owned cast, confirms private knowledge and restores stable identities without touching the world', async ({page}) => {
  test.setTimeout(120_000)
  let calls = 0
  await page.addInitScript(() => localStorage.setItem('storyforge_guide_completed', 'e2e'))
  await page.route('**/chat/completions', async route => {calls++; await route.abort()})
  await page.goto('./chat/library')
  const f = await page.evaluate(async () => {
    const load = new Function('p', 'return import(p)')
    const f = await (await load('/storyforge/tests/helpers/chat-narrative-production-fixture.ts')).seedChatNarrativeProductionFixture()
    const {db} = await load('/storyforge/src/lib/db/schema.ts')
    return {scope: f.scope, worldReleaseId: f.confirmed.worldReleaseId, world: JSON.stringify(await db.worldReleases.toArray())}
  })
  const query = `project=${f.scope.projectId}&work=${f.scope.workId}`
  await page.goto(`./chat/cast?${query}`)
  const cast = page.locator('section').filter({has: page.getByRole('heading', {name: '林舟', exact: true})}).last()
  await expect(page.getByRole('button', {name: '添加本体验新角色', exact: true})).toBeDisabled()
  await cast.getByLabel('参与本次聊天', {exact: true}).uncheck()
  await page.getByRole('button', {name: '添加本体验新角色', exact: true}).click()
  await page.getByLabel('新角色 1 姓名', {exact: true}).fill('苏禾')
  await page.getByLabel('新角色 1 身份', {exact: true}).fill('修钟铺店主')
  await page.getByLabel('新角色 1 经历与目标', {exact: true}).fill('希望修好旧钟，愿意自己检查工具。')
  await page.getByLabel('新角色 1 性格与顾虑', {exact: true}).fill('温和而有主见。')
  await page.getByLabel('新角色 1 说话方式', {exact: true}).fill('仅作者掌握的私域结局')
  await expect(cast.getByLabel('参与本次聊天', {exact: true})).toBeDisabled()
  await expect(page.getByRole('button', {name: '读取并检查完整资料', exact: true})).toBeDisabled()
  await page.getByRole('button', {name: '保存方案', exact: true}).click()
  await expect(page.getByText('方案已保存', {exact: true})).toBeVisible()
  await page.getByRole('button', {name: '读取并检查完整资料', exact: true}).click()
  await expect(page.locator('summary').filter({hasText: '苏禾本体验新角色'})).toBeVisible()
  await expect(page.getByLabel('苏禾 姓名 可见范围', {exact: true})).toHaveValue('unclassified')
  await page.getByLabel('苏禾 姓名 用途', {exact: true}).selectOption('identity')
  await page.getByLabel('苏禾 姓名 可见范围', {exact: true}).selectOption('public')
  await page.getByLabel('苏禾 背景 用途', {exact: true}).selectOption('motivation')
  await page.getByLabel('苏禾 背景 可见范围', {exact: true}).selectOption('participants')
  await page.getByLabel('苏禾 说话方式 可见范围', {exact: true}).selectOption('author-only')
  const preview = page.locator('details').filter({has: page.locator('summary').filter({hasText: '检查参与者实际获得的资料'})}).last()
  await preview.locator('summary').click()
  await expect(preview).not.toContainText('自己检查工具')
  await preview.getByRole('combobox').selectOption({label: '苏禾'})
  await expect(preview).toContainText('自己检查工具')
  await expect(preview).not.toContainText('仅作者掌握的私域结局')
  await page.getByRole('button', {name: '确认可见范围并用于新制作', exact: true}).click()
  await expect(page.getByText('已保存资料确认。更换角色或世界后需要重新检查。', {exact: true})).toBeVisible()
  await page.reload()
  await expect(page.getByLabel('新角色 1 姓名', {exact: true})).toHaveValue('苏禾')
  await page.getByRole('button', {name: '读取并检查完整资料', exact: true}).click()
  await expect(page.getByLabel('苏禾 背景 可见范围', {exact: true})).toHaveValue('participants')
  const result = await page.evaluate(async f => {
    const load = new Function('p', 'return import(p)')
    const {db} = await load('/storyforge/src/lib/db/schema.ts')
    const {readChatDraftV1} = await load('/storyforge/src/lib/character-interaction/draft-service.ts')
    const consultation = await load('/storyforge/src/lib/product-production/consultation.ts')
    const world = await load('/storyforge/src/lib/product-production/world-source.ts')
    const compiler = await load('/storyforge/src/lib/product-production/product-module-compilers.ts')
    const production = await load('/storyforge/src/lib/character-interaction/narrative-production.ts')
    const {hashProductProductionValueV2: hash} = await load('/storyforge/src/lib/product-production/hash.ts')
    const draft = await readChatDraftV1(f.scope), settings = JSON.parse(draft.settingsJson)
    const starting = await consultation.suggestProductStartingPoints({scope: f.scope, worldReleaseId: f.worldReleaseId})
    const brief = await consultation.draftProductProductionBriefV3({scope: f.scope, worldReleaseId: f.worldReleaseId,
      suggestionKey: starting.suggestions[0].suggestionKey, productType: 'character-interaction', characterChat: settings,
      playerRole: settings.playerRole, openingSituation: settings.openingSituation, visualLevel: 'none', audioLevel: 'none'})
    const sourceCatalog = await world.loadProductProductionWorldSourceCatalogV2({scope: f.scope, worldReleaseId: f.worldReleaseId, selection: brief.source.selection, chatPrivateCharacters: settings.privateCharacters})
    const prepared = compiler.prepareChatNarrativeCompilerSourceV1({brief, sourceCatalog})
    const {privateCharacters, ...reviewed} = settings
    const source = {schema: 'storyforge.chat-narrative-production-source', version: 1, settings: reviewed, source: prepared.content,
      participants: prepared.participantKeys.map((participantKey: string, i: number) => ({participantKey, characterKey: prepared.characterKeys[i], name: prepared.names[i], voiceRules: '自然说话'}))}
    const candidates = (await load('/storyforge/tests/helpers/chat-narrative-production-fixture.ts')).chatSituationCandidatesFixture(source)
    const content = await production.selectChatNarrativeCandidateV1({source, candidates, selection: {schema: 'storyforge.chat-situation-selection', version: 1, sourceHash: await hash(source), candidatesHash: await hash(candidates), selectedOptionKey: 'option-1', authorCommandId: 'author.choose'}})
    const compiled = compiler.compileInteractionModulesV1({brief, sourceCatalog, narrative: production.chatNarrativeShellV1(content), chatNarrative: content})
    const runtime = await load('/storyforge/src/lib/character-interaction/runtime.ts'), state = runtime.createInitialInteractionState(compiled)
    const beforeImport = JSON.stringify(await db.worldReleases.toArray())
    const transfer = await load('/storyforge/src/lib/export/json-export.ts')
    const importedId = await transfer.importProjectJSON(await transfer.exportProjectJSON(f.scope.projectId))
    const imported = await db.chatAuthoringDrafts.where('projectId').equals(importedId).first()
    return {characterKey: privateCharacters[0].characterKey, original: draft.settingsJson, imported: JSON.parse(imported.settingsJson), importedScope: {projectId: importedId, workId: imported.workId},
      compiled, beforeImport, player: runtime.interactionVisibilityView(state, 'player'), actor: runtime.interactionVisibilityView(state, state.profiles[0].participantKey)}
  }, f)
  expect(result.beforeImport).toBe(f.world)
  expect(result.imported.privateCharacters[0].characterKey).toBe(result.characterKey)
  expect(result.compiled.profiles[0]).toMatchObject({name: '苏禾', characterKey: result.characterKey})
  expect(result.compiled.chatSource.version).toBe(5)
  expect(JSON.stringify(result.compiled)).not.toContain('仅作者掌握的私域结局')
  expect(JSON.stringify(result.player)).not.toContain('自己检查工具')
  expect(JSON.stringify(result.actor)).toContain('自己检查工具')
  await page.goto(`./chat/cast?project=${result.importedScope.projectId}&work=${result.importedScope.workId}`)
  await page.setViewportSize({width: 390, height: 844})
  await expect(page.getByLabel('新角色 1 姓名', {exact: true})).toHaveValue('苏禾')
  expect(await page.evaluate(() => document.documentElement.scrollWidth - innerWidth)).toBeLessThanOrEqual(1)
  await page.getByLabel('新角色 1 经历与目标', {exact: true}).fill('今天决定先休息。')
  await page.getByRole('button', {name: '保存方案', exact: true}).click()
  await expect(page.getByText('开始新制作前，请检查并确认角色资料的可见范围。', {exact: true})).toBeVisible()
  await page.reload()
  await page.getByRole('button', {name: '读取并检查完整资料', exact: true}).click()
  await expect(page.getByLabel('苏禾 背景 可见范围', {exact: true})).toHaveValue('unclassified')
  const currentKey = await page.evaluate(async scope => {
    const load = new Function('p', 'return import(p)')
    const {db} = await load('/storyforge/src/lib/db/schema.ts')
    const draft = await db.chatAuthoringDrafts.where('workId').equals(scope.workId).first()
    return JSON.parse(draft.settingsJson).privateCharacters[0].characterKey
  }, result.importedScope)
  expect(currentKey).toBe(result.characterKey)
  await page.getByRole('button', {name: '移除新角色 1', exact: true}).click()
  await expect(page.getByTestId('chat-private-character')).toHaveCount(0)
  await page.getByRole('button', {name: '保存方案', exact: true}).click()
  await expect(page.getByText('方案已保存', {exact: true})).toBeVisible()
  await page.reload()
  await expect(page.getByTestId('chat-private-character')).toHaveCount(0)
  expect(await page.evaluate(async scope => {
    const load = new Function('p', 'return import(p)')
    return (await (await load('/storyforge/src/lib/character-interaction/draft-service.ts')).readChatDraftV1(scope)).settingsJson
  }, f.scope)).toBe(result.original)
  expect(calls).toBe(0)
})
