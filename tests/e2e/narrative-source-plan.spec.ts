import { gotoWithBrowserFixtureAIConfigV1, reloadWithBrowserFixtureAIConfigV1 } from './helpers/browser-ai-config'
import { expect, test } from '@playwright/test'
import { installNarrativeProductionFixtureV4, publishAndOpenNarrativeProductV4 } from './helpers/narrative-v4-production'

for (const product of ['chat', 'avg'] as const) {
  test(`NW-2C ${product} selects v4 sources, authorizes production, publishes and restores a real product session`, async ({ page }) => {
    test.setTimeout(180000)
    const fixtureCalls = await installNarrativeProductionFixtureV4(page, product)
    await page.addInitScript(() => localStorage.setItem('storyforge_guide_completed', 'e2e'))
    await gotoWithBrowserFixtureAIConfigV1(page, `./${product}/library`)
    const source = await page.evaluate(async () => {
      const load = new Function('path', 'return import(path)')
      const seeded = await (await load('/storyforge/tests/helpers/narrative-release-fixture.ts'))
        .seedNarrativeRelationReleaseV4({ explicitEntityEvidence: true })
      return { projectId: seeded.scope.projectId, hash: seeded.release.contentHash, release: seeded.release }
    })
    await gotoWithBrowserFixtureAIConfigV1(page, `./${product}/vision?narrative-preview=1`)
    await page.getByLabel(product === 'avg' ? 'AVG 作品名称' : '作品名称', { exact: true }).fill(`NW-2C ${product} 新版世界`)
    await page.getByLabel(product === 'avg' ? '玩家身份／主角' : '玩家身份', { exact: true }).fill('修桥见证人')
    await page.getByLabel(product === 'avg' ? '开场与核心目标' : '开场与场景目标', { exact: true }).fill('与守渡人商议修桥约定')
    await page.getByRole('button', { name: product === 'avg' ? '保存制作方案' : '保存方案', exact: true }).click()
    await expect(page).toHaveURL(/work=\d+.*narrative-preview/)
    const mainNav = () => page.getByRole('navigation', { name: product === 'avg' ? 'AVG 页面导航' : '角色聊天主导航' })
    await mainNav().getByRole('button', { name: '世界引擎', exact: true }).click()
    const experimentUrl = page.url()
    const ordinaryUrl = new URL(experimentUrl)
    ordinaryUrl.searchParams.delete('narrative-preview')
    await gotoWithBrowserFixtureAIConfigV1(page, ordinaryUrl.href)
    await expect(page.getByRole('heading', { name: '多段关系原文', exact: true })).toHaveCount(0)
    await gotoWithBrowserFixtureAIConfigV1(page, experimentUrl)
    const option = page.locator('article').filter({ has: page.getByRole('heading', { name: '多段关系原文', exact: true }) })
    await expect(option).toContainText('实验性')
    await option.getByRole('button', { name: '选择此版本', exact: true }).click()
    await expect(page.getByRole('status').filter({ hasText: product === 'avg' ? '世界版本已引用' : '已引用冻结世界版本' })).toBeVisible()
    await mainNav().getByRole('button', { name: '制作台', exact: true }).click()
    const contentNav = page.getByRole('navigation', { name: product === 'avg' ? 'AVG 内容导航' : '角色聊天页内目录' })
    if (product === 'chat') {
      await contentNav.getByRole('button', { name: '角色与场景', exact: true }).click()
      const actor = page.locator('section').filter({ has: page.getByRole('heading', { name: '守渡人', exact: true }) }).last()
      await actor.getByLabel('参与本次聊天').check()
      await page.getByRole('button', { name: '保存方案', exact: true }).click()
      await expect(page.getByRole('status')).toContainText('方案已保存')
      await page.getByRole('button', {name: '读取并检查完整资料', exact: true}).click()
      await page.getByLabel('守渡人 姓名 用途', {exact: true}).selectOption('identity')
      await page.getByLabel('守渡人 姓名 可见范围', {exact: true}).selectOption('public')
      await page.getByRole('button', {name: '确认可见范围并用于新制作', exact: true}).click()
      await expect(page.getByText('已保存资料确认。更换角色或世界后需要重新检查。', {exact: true})).toBeVisible()
      expect(fixtureCalls).toHaveLength(0)
    }
    await contentNav.getByRole('button', { name: '确认制作方案', exact: true }).click()
    await page.getByRole('button', { name: product === 'avg' ? '启用并继续确认' : '启用自动制作', exact: true }).click()
    // This source-contract route deliberately uses the supported text-only
    // product configuration, matching its no-media protocol fixture.
    if (product === 'avg') {
      await page.getByLabel('视觉目标').selectOption('none')
      await page.getByLabel('音频目标').selectOption('none')
    }
    await page.getByRole('button', { name: '分析可玩起点', exact: true }).click()
    await expect(page.getByRole('button', { name: '生成严格 Brief', exact: true })).toBeEnabled()
    await page.getByRole('button', { name: '生成严格 Brief', exact: true }).click()
    await expect(page.getByTestId('product-production-command-activity')).toContainText('succeeded')
    await page.getByRole('button', { name: '保存 Brief revision', exact: true }).click()
    await expect(page.getByText('r1 · 草稿', { exact: true })).toBeVisible()
    const read = () => page.evaluate(async () => {
      const load = new Function('path', 'return import(path)'), db = (await load('/storyforge/src/lib/db/schema.ts')).db
      const productionId = Number(new URLSearchParams(location.search).get('production'))
      const brief = await db.productProductionBriefs.where('[productionId+revision]').equals([productionId, 1]).first()
      const plan = await (await load('/storyforge/src/lib/product-production/source-contracts.ts')).parseProductProductionSourcePlanV1(brief)
      const release = await db.worldReleases.get(plan.worldReference.localReleaseRecordId)
      return { plan, projectId: release.projectId, release, selected: JSON.parse(brief.briefJson).source.selection }
    })
    const frozen = await read()
    expect(frozen.plan.version).toBe(2)
    expect(frozen.plan.worldReference.version).toBe(2)
    expect(frozen.selected.version).toBe(2)
    expect(frozen.plan.worldReference.releaseHash).toBe(source.hash)
    expect(frozen.projectId).not.toBe(source.projectId)
    expect(frozen.plan.exact.authorResourceKeys).toEqual([...frozen.selected.resourceKeys].sort())
    await reloadWithBrowserFixtureAIConfigV1(page)
    await expect(page.getByText('r1 · 草稿', { exact: true })).toBeVisible()
    expect(await read()).toEqual(frozen)
    const studioUrl = page.url()
    await publishAndOpenNarrativeProductV4(page, product, frozen.plan.planHash)
    expect([...fixtureCalls].sort()).toEqual(['content.design', 'content.narrative', 'content.product-module', 'media.requirements'].sort())
    const originalRelease = await page.evaluate(async releaseId => {
      const load = new Function('path', 'return import(path)'), db = (await load('/storyforge/src/lib/db/schema.ts')).db
      return db.worldReleases.get(releaseId)
    }, source.release.id)
    expect(originalRelease).toEqual(source.release)
    await gotoWithBrowserFixtureAIConfigV1(page, studioUrl)
    expect(await read()).toEqual(frozen)
  })
}

test('NW-2C AVG saves the exact source plan through author confirmation and preserves it after refresh', async ({ page }) => {
  test.setTimeout(120000)
  await page.addInitScript(() => localStorage.setItem('storyforge_guide_completed', 'e2e'))
  await gotoWithBrowserFixtureAIConfigV1(page, './avg/library')
  await page.evaluate(async () => {
    const load = new Function('path', 'return import(path)')
    await (await load('/storyforge/tests/helpers/current-product-world.ts')).seedCurrentProductWorld('NW-2C AVG 来源验证')
  })
  await gotoWithBrowserFixtureAIConfigV1(page, './avg/vision')
  await page.getByLabel('AVG 作品名称').fill('NW-2C 来源计划')
  await page.getByLabel('玩家身份／主角', { exact: true }).fill('灯塔档案员')
  await page.getByLabel('开场与核心目标').fill('和林舟核对港口的来信')
  await page.getByRole('button', { name: '保存制作方案', exact: true }).click()
  await expect(page).toHaveURL(/work=\d+/)
  const navigation = page.getByRole('navigation', { name: 'AVG 页面导航' })
  await navigation.getByRole('button', { name: '世界引擎', exact: true }).click()
  await page.getByRole('button', { name: '选择此版本', exact: true }).first().click()
  await expect(page.getByRole('status').filter({ hasText: '世界版本已引用' })).toBeVisible()
  await navigation.getByRole('button', { name: '制作台', exact: true }).click()
  await page.getByRole('navigation', { name: 'AVG 内容导航' }).getByRole('button', { name: '确认制作方案', exact: true }).click()
  await page.getByRole('button', { name: '启用并继续确认', exact: true }).click()
  await page.getByRole('button', { name: '分析可玩起点', exact: true }).click()
  await expect(page.getByRole('button', { name: '生成严格 Brief', exact: true })).toBeEnabled()
  await page.getByRole('button', { name: '生成严格 Brief', exact: true }).click()
  await expect(page.getByTestId('product-production-command-activity')).toContainText('succeeded')
  await page.getByRole('button', { name: '保存 Brief revision', exact: true }).click()
  await expect(page.getByText('r1 · 草稿', { exact: true })).toBeVisible()
  const readPlan = () => page.evaluate(async () => {
    const load = new Function('path', 'return import(path)')
    const db = (await load('/storyforge/src/lib/db/schema.ts')).db
    const productionId = Number(new URLSearchParams(location.search).get('production'))
    const row = await db.productProductionBriefs.where('[productionId+revision]').equals([productionId, 1]).first()
    if (!row) throw Error('Brief 没有完成持久化')
    const plan = await (await load('/storyforge/src/lib/product-production/source-contracts.ts')).parseProductProductionSourcePlanV1(row)
    return { plan, selected: JSON.parse(row.briefJson).source.selection.resourceKeys }
  })
  const first = await readPlan()
  expect(first.plan.version).toBe(2)
  expect(first.plan.compiler.compilerId).toBe('storyforge.avg.world-compiler')
  expect(first.plan.exact.authorResourceKeys).toEqual([...first.selected].sort())
  expect(first.plan.exact.requiredResourceKeys).toEqual([...new Set([
    ...first.plan.exact.authorResourceKeys, ...first.plan.exact.dependencyResourceKeys])].sort())
  await reloadWithBrowserFixtureAIConfigV1(page)
  await expect(page.getByText('r1 · 草稿', { exact: true })).toBeVisible()
  expect((await readPlan()).plan).toEqual(first.plan)
})
