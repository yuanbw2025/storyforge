import { expect, test } from '@playwright/test'

test('follow-up choices belong to each draft and unknown retries keep their identity across another completed report', async ({ page }) => {
  const posts: { body: Record<string, unknown>; wire: string }[] = []
  const unexpected: string[] = []
  await page.route('https://storyforge-lab.com/v1/client-support/**', async route => {
    const url = new URL(route.request().url())
    if (url.pathname.endsWith('/capabilities')) return route.fulfill({ json: { diagnosticContext: 1, feedbackForm: 2, feedbackImages: 1, feedbackFollowup: 1 } })
    if (url.pathname.endsWith('/feedback')) {
      const wire = route.request().postData()!, body = JSON.parse(wire)
      posts.push({ body, wire })
      if (posts.length === 1) return route.abort('failed')
      return route.fulfill({ json: { accepted: true, id: body.id } })
    }
    if (url.pathname.endsWith('/feedback-followup')) return route.fulfill({ status: 503, json: { error: 'ISOLATED_UNAVAILABLE' } })
    unexpected.push(url.pathname); return route.fulfill({ status: 503, json: {} })
  })
  await page.addInitScript(() => localStorage.setItem('storyforge_guide_completed', 'followup-choice-isolated'))
  await page.goto('home/settings')
  const panel = page.getByRole('region', { name: '问题与故障反馈' })
  const choice = panel.getByLabel('接收本条反馈的处理进展')
  await panel.getByRole('button', { name: '报告 Bug', exact: true }).click()
  await expect(choice).not.toBeChecked(); await choice.check()
  await panel.getByRole('button', { name: '功能建议', exact: true }).click()
  await expect(choice).not.toBeChecked()
  await panel.getByRole('button', { name: '报告 Bug', exact: true }).click()
  await expect(choice).toBeChecked()
  await page.evaluate(() => {
    const error = new TypeError('Cannot read properties of undefined')
    error.stack = 'TypeError: synthetic\n at x (http://localhost/storyforge/assets/fixture.js:2:34)'
    window.dispatchEvent(new ErrorEvent('error', { error }))
  })
  await panel.getByRole('button', { name: '查看故障摘要并反馈', exact: true }).click()
  await expect(panel.getByLabel('故障摘要预览')).toContainText('property-access')
  await panel.getByLabel('标题', { exact: true }).fill('Synthetic bug')
  await panel.getByLabel('涉及模块', { exact: true }).fill('反馈')
  await panel.getByLabel('问题描述', { exact: true }).fill('Synthetic report with no author content')
  await panel.getByLabel('复现步骤或触发场景', { exact: true }).fill('点击按钮')
  await panel.getByLabel('实际结果', { exact: true }).fill('操作失败')
  await panel.getByLabel('期望结果', { exact: true }).fill('操作成功')
  await panel.getByRole('button', { name: '提交反馈', exact: true }).click()
  await expect(panel).toContainText('提交结果未确认')
  await panel.getByRole('button', { name: '功能建议', exact: true }).click()
  await expect(choice).not.toBeChecked()
  await panel.getByLabel('标题', { exact: true }).fill('Synthetic suggestion')
  await panel.getByLabel('涉及模块', { exact: true }).fill('反馈')
  await panel.getByLabel('建议与使用场景', { exact: true }).fill('Synthetic suggestion without private data')
  await panel.getByLabel('希望怎样改进', { exact: true }).fill('操作成功')
  await panel.getByRole('button', { name: '提交反馈', exact: true }).click()
  await expect(panel).toContainText('提交成功')
  await panel.getByRole('button', { name: '报告 Bug', exact: true }).click()
  await expect(choice).toBeChecked()
  await panel.getByRole('button', { name: '提交反馈', exact: true }).click()
  await expect(panel).toContainText('提交成功')
  expect(posts).toHaveLength(3)
  expect(posts[0]!.body.diagnostics).toHaveLength(1)
  expect(posts[2]!.wire).toBe(posts[0]!.wire)
  expect(posts[1]!.body).not.toHaveProperty('followup')
  expect(posts[1]!.body).not.toHaveProperty('diagnostics')
  await panel.getByRole('button', { name: '报告 Bug', exact: true }).click()
  await expect(choice).not.toBeChecked()
  const receiptIds = await page.evaluate(() => JSON.parse(localStorage.getItem('storyforge_feedback_followup_v1')!).entries.map((row: { id: string }) => row.id))
  expect(receiptIds).toEqual([posts[0]!.body.id])
  expect(unexpected).toEqual([])
})
