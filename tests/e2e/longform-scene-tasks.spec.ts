import { expect, test } from '@playwright/test'
import { createLongform } from './helpers/product-entry'

test('同一章从章纲到任务细纲到正文再返回；快速编辑先保存，刷新与窄屏保留任务和备注', async ({ page }) => {
  await createLongform(page, '细纲任务与章节交接')
  await page.getByRole('button', { name: '大纲与章纲', exact: true }).click()
  await page.getByRole('button', { name: '添加卷', exact: true }).click()
  await page.getByRole('button', { name: '添加章节', exact: true }).click()
  await page.getByRole('textbox', { name: '章节摘要（可编辑，失焦自动保存）' }).fill('收店时明确明天分工，明早尚未开工。')
  await page.getByTitle('编辑本章细纲', { exact: true }).click()
  await expect(page).toHaveURL(/module=detailed-outline&chapter=\d+&work=\d+/)
  const chapterNode = new URL(page.url()).searchParams.get('chapter')
  const workId = new URL(page.url()).searchParams.get('work')
  await expect(page.getByRole('heading', { name: '📝 第1章', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '添加场景', exact: true }).click()
  await expect(page.getByRole('button', { name: '第1章', exact: true })).toHaveAttribute('aria-description', '未规划')
  await page.getByPlaceholder('一句话场景概要...', { exact: true }).fill('两人边擦桌边约好明早分工。')
  await page.getByText('场景任务（可选，可留白）', { exact: true }).click()
  await page.getByLabel('场景1 · 本场目标', { exact: true }).pressSequentially('让两个人愿意分工')
  await page.getByLabel('场景1 · 关键选择', { exact: true }).fill('先问搭档的意愿')
  await page.getByLabel('场景1 · 退出状态', { exact: true }).fill('约定已达成，明天仍未开始干活')
  await page.getByPlaceholder('备注 / AI 建议...', { exact: true }).fill('保留缓冲场景，不增加敌人。')
  await page.getByRole('button', { name: '写本章正文', exact: true }).click()
  await expect(page).toHaveURL(new RegExp(`module=chapters-list&chapter=${chapterNode}&work=${workId}`))
  await expect(page.getByRole('heading', { name: '第1章', exact: true, level: 2 })).toBeVisible()
  await page.locator('.tiptap-editor').fill('两人把明早分工定下来，关灯回家。')
  await page.getByRole('button', { name: '查看本章细纲', exact: true }).click()
  await expect(page).toHaveURL(new RegExp(`module=detailed-outline&chapter=${chapterNode}&work=${workId}`))
  await expect(page.getByRole('button', { name: '第1章', exact: true })).toHaveAttribute('aria-description', '已保存细纲')
  await page.getByText('场景任务（可选，可留白）', { exact: true }).click()
  await expect(page.getByLabel('场景1 · 本场目标', { exact: true })).toHaveValue('让两个人愿意分工')
  await expect(page.getByPlaceholder('备注 / AI 建议...', { exact: true })).toHaveValue('保留缓冲场景，不增加敌人。')
  await page.reload()
  await page.getByText('场景任务（可选，可留白）', { exact: true }).click()
  await expect(page.getByLabel('场景1 · 退出状态', { exact: true })).toHaveValue('约定已达成，明天仍未开始干活')
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.locator('main').evaluate(element => element.scrollWidth <= element.clientWidth + 1)).toBe(true)
  await page.getByRole('button', { name: '查看本章章纲', exact: true }).click()
  await expect(page).toHaveURL(new RegExp(`module=outline&chapter=${chapterNode}&work=${workId}`))
  await page.getByRole('textbox', { name: '章节摘要（可编辑，失焦自动保存）' }).fill('章纲调整为先核实库存，再安排分工。')
  await page.getByTitle('编辑本章细纲', { exact: true }).click()
  await expect(page.getByRole('button', { name: '第1章', exact: true })).toHaveAttribute('aria-description', '章纲变化待复核')
  await expect(page.getByText('大纲已变更', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: '我已复核', exact: true }).click()
  await expect(page.getByRole('button', { name: '第1章', exact: true })).toHaveAttribute('aria-description', '已保存细纲')
  await page.getByRole('button', { name: '写本章正文', exact: true }).click()
  await expect(page.locator('.tiptap-editor')).toHaveText('两人把明早分工定下来，关灯回家。')
  const foreignURL = new URL(page.url()); foreignURL.searchParams.set('work', String(Number(workId) + 100))
  await page.goto(foreignURL.toString())
  await expect(page.getByRole('alert')).toContainText('章节跳转属于其它作品')
  await expect(page.locator('.tiptap-editor')).toHaveCount(0)
})

test('新任务字段走原细纲 Harness；候选在其它章节仍有标记，刷新恢复，拒绝零写入，编辑采纳后才正式保存', async ({ page }) => {
  await page.addInitScript(() => localStorage.setItem('storyforge-ai-config', JSON.stringify({ provider: 'ollama', baseUrl: 'https://scene-tasks.invalid/v1', model: 'task-contract-test', maxTokens: 4000, temperature: 0 })))
  const output = { scenePlanMode: 'replace', scenes: [{ action: 'add', title: '收店约定', summary: '两人收店后安排明天的分工', location: '小店', conflict: '', pace: 'slow', estimatedWords: 600, characterIds: [], entryState: '分工未定', goal: '明确分工', keyChoice: '先问搭档意愿', outcome: '达成约定', exitState: '约定未履行', sceneFunction: '关系缓冲', notes: '不要追加敌人' }] }
  let calls = 0
  await page.route('https://scene-tasks.invalid/**', async route => {
    calls++
    expect(route.request().postDataJSON().messages.map((row: { content: string }) => row.content).join('\n')).toContain('entryState')
    await route.fulfill({ contentType: 'text/event-stream', body: `data: ${JSON.stringify({ choices: [{ delta: { content: JSON.stringify(output) } }] })}\n\ndata: [DONE]\n\n` })
  })
  await createLongform(page, '细纲任务候选隔离验收')
  await page.getByRole('button', { name: '大纲与章纲', exact: true }).click()
  await page.getByRole('button', { name: '添加卷', exact: true }).click()
  await page.getByRole('button', { name: '添加章节', exact: true }).click()
  await page.getByRole('textbox', { name: '章节摘要（可编辑，失焦自动保存）' }).fill('收店后约定分工，尚未兑现。')
  await page.getByRole('button', { name: '添加章节', exact: true }).click()
  await page.getByRole('button', { name: '场景细纲', exact: true }).click()
  await page.getByRole('button', { name: '第1章', exact: true }).click()
  await page.getByRole('button', { name: 'AI 一键拆场景', exact: true }).click()
  const draft = page.getByRole('textbox', { name: 'AI 候选可编辑内容', exact: true })
  await expect(draft).toHaveValue(JSON.stringify(output))
  await expect(page.getByRole('button', { name: '第1章', exact: true })).toHaveAttribute('aria-description', '有待确认候选')
  await expect(page.getByPlaceholder('场景标题...', { exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: '第2章', exact: true }).click()
  await expect(page.getByRole('heading', { name: '📝 第2章', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: '第1章', exact: true })).toHaveAttribute('aria-description', '有待确认候选')
  await page.getByRole('button', { name: '第1章', exact: true }).click()
  await page.reload()
  await page.getByRole('button', { name: '第1章', exact: true }).click()
  await expect(draft).toHaveValue(JSON.stringify(output))
  await page.getByTitle('关闭，保留原文不采纳', { exact: true }).click()
  await expect(draft).toHaveCount(0)
  await expect(page.getByPlaceholder('场景标题...', { exact: true })).toHaveCount(0)
  await expect(page.getByRole('button', { name: '第1章', exact: true })).toHaveAttribute('aria-description', '未规划')
  await page.reload()
  await page.getByRole('button', { name: '第1章', exact: true }).click()
  await expect(draft).toHaveCount(0)
  await page.getByRole('button', { name: 'AI 一键拆场景', exact: true }).click()
  await expect(draft).toHaveValue(JSON.stringify(output))
  const revised = { ...output, scenes: [{ ...output.scenes[0], goal: '作者确认的分工目标' }] }
  await draft.fill(JSON.stringify(revised))
  await page.getByRole('button', { name: '采纳', exact: true }).click()
  await expect(draft).toHaveCount(0)
  await page.getByText('场景任务（可选，可留白）', { exact: true }).click()
  await expect(page.getByLabel('场景1 · 本场目标', { exact: true })).toHaveValue('作者确认的分工目标')
  await expect(page.getByLabel('场景1 · 退出状态', { exact: true })).toHaveValue('约定未履行')
  await expect(page.getByPlaceholder('备注 / AI 建议...', { exact: true })).toHaveValue('不要追加敌人')
  expect(calls).toBe(2)
})
