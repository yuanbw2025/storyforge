import {test, expect} from '@playwright/test'

test('author maps a world player separately from AI cast and confirms private player history before compiling', async ({page}) => {
  let calls = 0
  await page.addInitScript(() => localStorage.setItem('storyforge_guide_completed', 'e2e'))
  await page.route('**/chat/completions', async route => {calls++; await route.abort()})
  await page.goto('./chat/library')
  const f = await page.evaluate(async () => {
    const load = new Function('p', 'return import(p)')
    const f = await (await load('/storyforge/tests/helpers/chat-narrative-production-fixture.ts')).seedChatNarrativeProductionFixture()
    const index = await (await load('/storyforge/src/lib/product-production/world-source.ts')).loadProductProductionConsultationSourceV2({scope: f.scope, worldReleaseId: f.confirmed.worldReleaseId})
    return {scope: f.scope, ai: f.settings.characters[0].sourceKey, worldReleaseId: f.confirmed.worldReleaseId,
      player: index.selectionOptions.characters.find((c: {label: string}) => c.label === '守潮人').resourceKey}
  })
  const query = `project=${f.scope.projectId}&work=${f.scope.workId}`
  await page.goto(`./chat/vision?${query}`)
  await expect(page.getByRole('combobox', {name: '玩家人物来源', exact: true})).toHaveValue('')
  await expect(page.getByRole('combobox', {name: '玩家人物来源', exact: true}).locator(`option[value="${f.ai}"]`)).toHaveJSProperty('disabled', true)
  await page.getByRole('combobox', {name: '玩家人物来源', exact: true}).selectOption(f.player)
  await page.getByLabel('玩家虚构角色的称呼', {exact: true}).fill('守潮人')
  await page.getByLabel('玩家身份', {exact: true}).fill('来修钟铺借书的守潮人，尚未答应修理。')
  await page.getByRole('button', {name: '保存方案', exact: true}).click()
  await expect(page.getByText('方案已保存', {exact: true})).toBeVisible()
  await page.goto(`./chat/cast?${query}`)
  const playerCast = page.locator('section').filter({has: page.getByRole('heading', {name: '守潮人', exact: true})}).last()
  await expect(playerCast.getByLabel('参与本次聊天', {exact: true})).toBeDisabled()
  await expect(playerCast).toContainText('此人物由玩家扮演')
  await page.getByRole('button', {name: '读取并检查完整资料', exact: true}).click()
  await expect(page.getByLabel('守潮人 背景 可见范围', {exact: true})).toHaveValue('unclassified')
  expect(await page.getByLabel('守潮人 背景 用途', {exact: true}).locator('option').evaluateAll(options => options.map(option => (option as HTMLOptionElement).value))).toEqual(['identity', 'knowledge'])
  await page.getByLabel('守潮人 姓名 可见范围', {exact: true}).selectOption('public')
  await page.getByLabel('守潮人 姓名 用途', {exact: true}).selectOption('identity')
  await page.getByLabel('守潮人 背景 可见范围', {exact: true}).selectOption('participants')
  await page.getByLabel('林舟 姓名 可见范围', {exact: true}).selectOption('public')
  const playerSource = page.locator('details').filter({has: page.locator('summary').filter({hasText: '玩家扮演'})}).first()
  await expect(playerSource.getByLabel('玩家', {exact: true})).toBeChecked()
  await expect(playerSource.getByLabel('林舟', {exact: true})).not.toBeChecked()
  const preview = page.locator('details').filter({has: page.locator('summary').filter({hasText: '检查参与者实际获得的资料'})}).last()
  await preview.locator('summary').click()
  await expect(preview).toContainText('来自旧港议会')
  await preview.getByRole('combobox').selectOption(f.ai)
  await expect(preview).not.toContainText('来自旧港议会')
  await expect(preview).not.toContainText('知道失踪船队真相')
  await page.getByRole('button', {name: '确认可见范围并用于新制作', exact: true}).click()
  await expect(page.getByText('已保存资料确认。更换角色或世界后需要重新检查。', {exact: true})).toBeVisible()
  await page.reload()
  await page.getByRole('button', {name: '读取并检查完整资料', exact: true}).click()
  await expect(page.getByLabel('守潮人 背景 可见范围', {exact: true})).toHaveValue('participants')
  const installed = await page.evaluate(async f => {
    const load = new Function('p', 'return import(p)')
    const service = await load('/storyforge/src/lib/character-interaction/draft-service.ts')
    const consultation = await load('/storyforge/src/lib/product-production/consultation.ts')
    const sourceService = await load('/storyforge/src/lib/product-production/world-source.ts')
    const compiler = await load('/storyforge/src/lib/product-production/product-module-compilers.ts')
    const production = await load('/storyforge/src/lib/character-interaction/narrative-production.ts')
    const hash = (await load('/storyforge/src/lib/product-production/hash.ts')).hashProductProductionValueV2
    const draft = await service.readChatDraftV1(f.scope), settings = JSON.parse(draft.settingsJson)
    const starting = await consultation.suggestProductStartingPoints({scope: f.scope, worldReleaseId: f.worldReleaseId})
    const brief = await consultation.draftProductProductionBriefV3({scope: f.scope, worldReleaseId: f.worldReleaseId, suggestionKey: starting.suggestions[0].suggestionKey,
      productType: 'character-interaction', characterChat: settings, playerRole: settings.playerRole, openingSituation: settings.openingSituation, visualLevel: 'none', audioLevel: 'none'})
    const sourceCatalog = await sourceService.loadProductProductionWorldSourceCatalogV2({scope: f.scope, worldReleaseId: f.worldReleaseId, selection: brief.source.selection})
    const prepared = compiler.prepareChatNarrativeCompilerSourceV1({brief, sourceCatalog})
    const source = {schema: 'storyforge.chat-narrative-production-source', version: 1, settings, source: prepared.content,
      participants: prepared.participantKeys.map((participantKey: string, i: number) => ({participantKey, characterKey: prepared.characterKeys[i], name: prepared.names[i], voiceRules: '自然说话'}))}
    const candidates = (await load('/storyforge/tests/helpers/chat-narrative-production-fixture.ts')).chatSituationCandidatesFixture(source)
    const content = await production.selectChatNarrativeCandidateV1({source, candidates, selection: {schema: 'storyforge.chat-situation-selection', version: 1, sourceHash: await hash(source), candidatesHash: await hash(candidates), selectedOptionKey: 'option-1', authorCommandId: 'author.choose'}})
    const compiled = compiler.compileInteractionModulesV1({brief, sourceCatalog, narrative: production.chatNarrativeShellV1(content), chatNarrative: content})
    const runtime = await load('/storyforge/src/lib/character-interaction/runtime.ts'), state = runtime.createInitialInteractionState(compiled)
    return {persona: state.chatNarrative.persona, profiles: state.profiles, source: compiled.chatSource,
      playerView: runtime.interactionVisibilityView(state, 'player'), aiView: runtime.interactionVisibilityView(state, state.profiles[0].participantKey)}
  }, f)
  expect(installed.persona).toMatchObject({name: '守潮人', origin: 'world-character', source: {resourceKey: f.player}})
  expect(installed.source.version).toBe(3)
  expect(installed.profiles).toHaveLength(1)
  expect(installed.profiles[0].characterKey).toBe(f.ai)
  expect(JSON.stringify(installed.playerView)).toContain('来自旧港议会')
  expect(JSON.stringify(installed.aiView)).not.toContain('来自旧港议会')
  await page.setViewportSize({width: 390, height: 844})
  expect(await page.evaluate(() => document.documentElement.scrollWidth - innerWidth)).toBeLessThanOrEqual(1)
  await page.goto(`./chat/vision?${query}`)
  await expect(page.getByRole('combobox', {name: '玩家人物来源', exact: true})).toHaveValue(f.player)
  await page.getByRole('combobox', {name: '玩家人物来源', exact: true}).selectOption('')
  await page.getByRole('button', {name: '保存方案', exact: true}).click()
  await expect(page.getByText('方案已保存', {exact: true})).toBeVisible()
  await page.goto(`./chat/cast?${query}`)
  await expect(page.getByText('开始新制作前，请检查并确认角色资料的可见范围。', {exact: true})).toBeVisible()
  await expect(playerCast.getByLabel('参与本次聊天', {exact: true})).toBeEnabled()
  expect(calls).toBe(0)
})
