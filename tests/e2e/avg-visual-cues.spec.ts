import { test,expect } from '@playwright/test'

test('authored visual effects follow their own cue identity, duration, pause and camera state without replay on uncued lines',async({page},info)=>{
  test.setTimeout(120_000)
  await page.addInitScript(()=>localStorage.setItem('storyforge_guide_completed','e2e'))
  await page.goto('./avg/library');await expect(page.getByRole('button',{name:'新建 AVG',exact:true})).toBeVisible({timeout:30_000})
  const s=await page.evaluate(async()=>{
    const load=new Function('p','return import(p)') as(p:string)=>Promise<any>
    return(await load('/storyforge/tests/helpers/avg-release-fixture.ts')).prepareAvgMediaReleasePreview((workspace:any)=>{
      const source=workspace.scripts[0].lines[0]
      workspace.scripts[0].lines.push({...source,lineKey:'line.dark.plain',beatKey:'line.dark.plain',text:'这一句没有闪光或震动。'},
        {...source,lineKey:'line.dark.motion',beatKey:'line.dark.motion',text:'这一句再次震动，镜头位置应保持。'})
      const add=(cueKey:string,beatKey:string,type:string,durationMs:number,extra={})=>workspace.presentation.stage.cues.push({cueKey,beatKey,type,durationMs,phase:'before',order:10,easing:'linear',...extra})
      add('flash.first','line.dark','flash',750,{order:11})
      add('shake.first','line.dark','shake',800)
      add('camera.first','line.dark','camera',400,{x:2,y:1,scale:1.2})
      add('shake.again','line.dark.motion','shake',1600)
      add('fade.after','line.dark.motion','transition',1200,{phase:'after',order:11})
      add('hold.after','line.dark.motion','wait',1500,{phase:'after',order:12})
    })
  })
  await page.goto(`./avg/play?project=${s.scope.projectId}&work=${s.scope.workId}&session=${s.sessionId}`)
  await expect(page.locator('.avg-flash')).toHaveCount(1)
  await expect(page.locator('.avg-text-cursor')).toHaveClass(/is-complete/)
  const retry=page.getByRole('button',{name:'重试配音',exact:true});if(await retry.isVisible())await retry.click()
  await expect.poll(()=>page.evaluate(async id=>{const load=new Function('p','return import(p)') as(p:string)=>Promise<any>;return(await(await load('/storyforge/src/lib/product/runtime-core.ts')).readProductRuntimeState(id)).avgReading.current.status},s.sessionId)).toBe('ended')
  await page.getByRole('button',{name:'继续',exact:true}).click()
  await expect(page.locator('.avg-dialogue p')).toHaveText('这一句没有闪光或震动。')
  await expect(page.locator('.avg-flash')).toHaveCount(0)
  const camera=await page.locator('.avg-stage-scene').evaluate(element=>getComputedStyle(element).transform)
  expect(camera).not.toBe('none')
  await page.getByRole('button',{name:'继续',exact:true}).click()
  await expect(page.locator('.avg-dialogue p')).toHaveText('这一句再次震动，镜头位置应保持。')
  await expect.poll(()=>page.locator('.avg-stage-scene').evaluate(element=>element.getAnimations().some(animation=>animation.playState==='running'&&animation.effect?.getTiming().duration===1600))).toBe(true)
  await page.getByRole('button',{name:'历史',exact:true}).click()
  await expect.poll(()=>page.locator('.avg-stage-scene').evaluate(element=>element.getAnimations().some(animation=>animation.playState==='paused'))).toBe(true)
  await page.getByRole('dialog',{name:'历史回看'}).getByRole('button',{name:'关闭',exact:true}).click()
  await expect.poll(()=>page.locator('.avg-stage-scene').evaluate(element=>element.getAnimations().some(animation=>animation.playState==='running'))).toBe(true)
  await expect.poll(()=>page.locator('.avg-stage-scene').evaluate(element=>getComputedStyle(element).transform)).toBe(camera)
  await page.locator('summary[aria-label="设置"]').click()
  await page.getByRole('button',{name:'减少动态',exact:true}).click()
  await expect.poll(()=>page.locator('.avg-stage-scene').evaluate(element=>element.getAnimations().length)).toBe(0)
  expect(await page.locator('.avg-dialogue p').textContent()).toBe('这一句再次震动，镜头位置应保持。')
  await page.getByRole('button',{name:'减少动态',exact:true}).click()
  await expect.poll(()=>page.locator('.avg-stage-scene').evaluate(element=>element.getAnimations().length)).toBe(0)
  await page.locator('summary[aria-label="设置"]').click()
  await expect.poll(()=>page.locator('.avg-dialogue').evaluate(element=>getComputedStyle(element).opacity)).toBe('1')
  await page.screenshot({path:info.outputPath('avg-visual-cue-camera.png')})
  await page.getByRole('button',{name:'继续',exact:true}).click()
  await expect.poll(()=>page.locator('.avg-stage-scene').evaluate(element=>element.getAnimations().some(animation=>animation.effect?.getTiming().duration===1200))).toBe(true)
  await expect(page.getByRole('button',{name:'打开灯光',exact:true})).toBeVisible()
})
