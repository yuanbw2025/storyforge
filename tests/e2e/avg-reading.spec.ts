import { expect, test, type Page } from '@playwright/test'

async function prepare(page: Page, manualVoice: 'wait' | 'interrupt', broken = false, duration = 2800, maximum = 10_000, sfx = false) {
  await page.addInitScript(() => localStorage.setItem('storyforge_guide_completed', 'e2e'))
  await page.goto('./avg/library')
  const owned = await page.evaluate(async options => {
    const load = new Function('path', 'return import(path)') as (path: string) => Promise<any>
    const [fixture, runtime] = await Promise.all([load('/storyforge/tests/helpers/avg-reading-fixture.ts'), load('/storyforge/src/lib/product/runtime-instances.ts')])
    const s = await fixture.seedAvgReadingPreview({ manualVoice: options.manualVoice, maximumVoiceWaitMs: options.maximum }, options.duration, options.broken, options.sfx)
    const session = await runtime.createProductRuntimeInstance({ scope: s.scope, kind: 'avg', title: '真实音频协调测试（校准音）',
      productSource: { kind: 'build', productBuildId: s.buildId, expectedPreviewHash: s.preview.previewHash } })
    return { scope: s.scope, sessionId: session.id }
  }, { manualVoice, broken, duration, maximum, sfx })
  await page.goto(`./avg/play?project=${owned.scope.projectId}&work=${owned.scope.workId}&session=${owned.sessionId}`)
  await expect(page.locator('.avg-dialogue p')).toHaveText('封口仍在。')
  return owned
}
async function state(page: Page) {
  return page.evaluate(async () => {
    const load = new Function('path', 'return import(path)') as (path: string) => Promise<any>
    const [runtime, player] = await Promise.all([load('/storyforge/src/lib/product/runtime-core.ts'), load('/storyforge/src/stores/avg-game-player.ts')])
    return runtime.readProductRuntimeState(player.useAvgGamePlayerStore.getState().selectedSessionId)
  })
}
async function ensurePlaying(page: Page) {
  // Retry browser audio permission through the actual button when needed.
  // No media API, ended event, duration or transport result is mocked.
  const retry = page.getByRole('button', { name: '重试配音', exact: true })
  await expect.poll(async () => await retry.isVisible() || await page.locator('audio[data-channel="voice"]').evaluate((a: HTMLAudioElement) => !a.paused && a.currentTime > .05)).toBe(true)
  if (await retry.isVisible()) await retry.click()
  await expect.poll(() => page.locator('audio[data-channel="voice"]').evaluate((a: HTMLAudioElement) => !a.paused && a.currentTime > .05)).toBe(true)
}
test('real PCM ended gates auto; menus pause transport; repeated history, replay, refresh and fork preserve the actual state', async ({ page }, info) => {
  await prepare(page,'wait')
  await ensurePlaying(page)
  await page.getByRole('button', { name: '自动播放', exact: true }).click()
  await page.getByRole('button', { name: '历史', exact: true }).click()
  const audio = page.locator('audio[data-channel="voice"]')
  await expect.poll(() => audio.evaluate((a: HTMLAudioElement) => a.paused)).toBe(true)
  const pausedTime = await audio.evaluate((a: HTMLAudioElement) => a.currentTime)
  await page.waitForTimeout(500)
  expect(await audio.evaluate((a: HTMLAudioElement) => a.currentTime)).toBeLessThan(pausedTime+.1)
  expect((await state(page)).avgReading.history).toHaveLength(0)
  await page.getByRole('dialog', { name: '历史回看' }).getByRole('button', { name: '关闭', exact: true }).click()
  await expect(page.getByRole('button', { name: '检查封口', exact: true })).toBeVisible()
  expect((await state(page)).avgReading.history[0].voiceOutcome).toBe('ended')
  expect((await state(page)).avgReading.history[0].voicePlayedMs).toBeGreaterThanOrEqual(2700)
  await page.getByRole('button', { name: '检查封口', exact: true }).click()
  await expect.poll(async () => (await state(page)).avgReading.history.length).toBe(3)
  await expect(page.getByRole('button', { name: '检查封口', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: '检查封口', exact: true })).toBeDisabled()
  await page.getByRole('button', { name: '历史', exact: true }).click()
  const history = page.getByRole('dialog', { name: '历史回看' })
  await expect(history.locator('article')).toHaveCount(3)
  await expect(history.locator('article').nth(1)).toContainText('检查封口')
  const beforeReplay = await state(page)
  await history.getByRole('button', { name: '回听第 1 条', exact: true }).click()
  await expect.poll(() => page.locator('audio[data-channel="history"]').evaluate((a: HTMLAudioElement) => !a.paused && a.currentTime > .05)).toBe(true)
  await history.getByRole('button', { name: '停止回听', exact: true }).click()
  expect(await state(page)).toEqual(beforeReplay)
  await page.screenshot({ path: info.outputPath('avg-reading-history.png'), fullPage: true })
  await history.getByRole('button', { name: '关闭', exact: true }).click()
  await page.getByRole('button', { name: '快速存档', exact: true }).click()
  await expect(page.getByRole('status').filter({ hasText: '已快速存档' })).toBeVisible()
  await page.reload()
  await expect(page.getByRole('button', { name: '向保管员说明', exact: true })).toBeVisible()
  expect((await state(page)).avgReading.history).toHaveLength(3)
  await expect(page.locator('audio[data-channel="voice"]')).toHaveCount(0)
  await page.getByRole('button', { name: '存读档', exact: true }).click()
  await page.getByRole('button', { name: '从这里开始新分支' }).first().click()
  await page.getByRole('button', { name: '历史', exact: true }).click()
  await page.getByRole('dialog', { name: '历史回看' }).getByRole('button', { name: '回听第 1 条', exact: true }).click()
  await expect.poll(() => page.locator('audio[data-channel="history"]').evaluate((a: HTMLAudioElement) => !a.paused && a.currentTime > .05)).toBe(true)
})
