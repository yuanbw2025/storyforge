test('a real decoder failure pauses auto, retries a new generation, then continues only after explicit confirmation', async ({ page }) => {
  await prepare(page,'interrupt',true)
  await page.getByRole('button', { name: '自动播放', exact: true }).click()
  await expect(page.getByRole('button', { name: '重试配音', exact: true })).toBeVisible()
  const failed = await state(page)
  expect(failed.avgReading.current.status).toBe('failed')
  expect(failed.avgReading.history).toHaveLength(0)
  await page.getByRole('button', { name: '重试配音', exact: true }).click()
  await expect.poll(async () => (await state(page)).avgReading.current.generation).not.toBe(failed.avgReading.current.generation)
  await expect(page.getByRole('button', { name: '静音继续', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '静音继续', exact: true }).click()
  await expect(page.getByRole('button', { name: '检查封口', exact: true })).toBeVisible()
  expect((await state(page)).avgReading.history[0].voiceOutcome).toBe('interrupted')
})
test('active playback has a bounded failure timeout and never fabricates ended', async ({ page }) => {
  await prepare(page,'wait',false,7000,2000)
  await ensurePlaying(page)
  await expect(page.getByRole('status').filter({ hasText: '音频播放等待超时' })).toBeVisible()
  const value = await state(page)
  expect(value.avgReading.current.status).toBe('failed')
  expect(value.avgReading.current.playedMs).toBeGreaterThan(0)
  expect(value.avgReading.history).toHaveLength(0)
  await expect.poll(() => page.locator('audio[data-channel="voice"]').evaluate((a: HTMLAudioElement) => a.paused)).toBe(true)
})
test('reader channel volumes and delay survive refresh without restarting automatic reading', async ({ page }) => {
  await prepare(page,'wait')
  await page.locator('.avg-settings summary').click()
  await expect.poll(() => page.locator('audio[data-channel="voice"]').evaluate((a: HTMLAudioElement) => a.paused)).toBe(true)
  const voice = page.getByRole('slider', { name: '配音音量', exact: true })
  await voice.press('Home'); await voice.press('ArrowRight')
  const delay = page.getByRole('slider', { name: '自动阅读余量', exact: true })
  await delay.press('Home'); await delay.press('ArrowRight')
  await expect(voice).toHaveValue('0.05'); await expect(delay).toHaveValue('100')
  await expect.poll(() => page.locator('audio[data-channel="voice"]').evaluate((a: HTMLAudioElement) => a.volume)).toBeCloseTo(.04,3)
  await page.reload()
  await page.locator('.avg-settings summary').click()
  await expect(page.getByRole('slider', { name: '配音音量', exact: true })).toHaveValue('0.05')
  await expect(page.getByRole('slider', { name: '自动阅读余量', exact: true })).toHaveValue('100')
  await expect(page.getByRole('button', { name: '自动播放', exact: true })).toHaveAttribute('aria-pressed','false')
})

test('distinct sound Cues replay the same clip once each, and a settled save does not replay old effects', async ({ page }) => {
  await prepare(page,'wait',false,1800,10_000,true)
  await ensurePlaying(page)
  await expect.poll(async () => (await state(page)).avgReading.current.status).toBe('ended')
  await page.getByRole('button', { name: '继续', exact: true }).click()
  await expect.poll(() => page.locator('audio[data-channel="sfx"]').evaluate((a: HTMLAudioElement) => !a.paused && a.currentTime > .05 && a.currentTime < .9)).toBe(true)
  await expect(page.getByRole('button', { name: '检查封口', exact: true })).toBeVisible()
  await expect(page.locator('audio[data-channel="sfx"]')).toHaveCount(0)
  await page.getByRole('button', { name: '快速存档', exact: true }).click()
  await expect(page.getByRole('status').filter({ hasText: '已快速存档' })).toBeVisible()
  await page.reload()
  await expect(page.getByRole('button', { name: '检查封口', exact: true })).toBeVisible()
  await expect(page.locator('audio[data-channel="sfx"]')).toHaveCount(0)
})
test('loading a mid-clip checkpoint starts a new generation from the sentence and rejects old-session transport', async ({ page }) => {
  const owned = await prepare(page,'wait',false,5000)
  await ensurePlaying(page)
  await page.getByRole('button', { name: '快速存档', exact: true }).click()
  await expect(page.getByRole('status').filter({ hasText: '已快速存档' })).toBeVisible()
  const parent = await state(page)
  await page.getByRole('button', { name: '存读档', exact: true }).click()
  await page.getByRole('button', { name: '从这里开始新分支' }).first().click()
  await expect.poll(async () => (await state(page)).avgReading.current.generation).not.toBe(parent.avgReading.current.generation)
  await expect.poll(() => page.locator('audio[data-channel="voice"]').evaluate((a: HTMLAudioElement) => !a.paused && a.currentTime > .05 && a.currentTime < 1.5)).toBe(true)
  const projection = await page.evaluate(async id => {
    const load = new Function('path', 'return import(path)') as (path: string) => Promise<any>
    const [player, runtime] = await Promise.all([load('/storyforge/src/stores/avg-game-player.ts'), load('/storyforge/src/lib/product/runtime-core.ts')])
    const s = player.useAvgGamePlayerStore.getState()
    return { selected: s.selectedSessionId, source: s.selectedSourceSessionId, parent: await runtime.readProductRuntimeState(id) }
  }, owned.sessionId)
  expect(projection.selected).not.toBe(owned.sessionId)
  expect(projection.selected).toBe(projection.source)
  expect(projection.parent.avgReading.current.status).toBe('requested')
  expect(projection.parent.avgReading.history).toHaveLength(0)
})
